"""pragmatic_speaker — the THIRD piece of the communication loop: the SPEAKER MODELLING THE
LISTENER. donkey=0, earn-not-borrow, graph-native.

THE ARC HOLDS TWO OF THREE PIECES:
  (1) LISTENER  = analysis-by-synthesis / fused recognizer (invert the generator to recover the
                  message): domains/analysis_by_synthesis + domains/abs_learned_fusion.
  (2) SPEAKER (cost-minimal) = writer-physics, the thermodynamically-cheapest motor trajectory
                  that makes the shape: domains/earned_augmentation.generate_physical_variant +
                  motor_stats (minimum-jerk / two-thirds-law effort).
MISSING (3): the SPEAKER CHOOSING ITS ENCODING SO THE AUDIENCE CAN INVERT IT. This module adds it.

THE TWO-MODEL INSIGHT (the creator's): a signal only needs to carry the RESIDUAL between what you
mean and what the audience already predicts from ITS model. A pure cost-minimal writer scrawls
illegibly (cheap to PRODUCE, impossible to DECODE); a fully-explicit writer wastes effort. The
MIDPOINT is the JOINT optimum of production-cost (speaker) AND decoding-risk (audience):

    J(signal) = ListenerRecovery(signal)  -  lambda * ProductionCost(signal)

The argmax over a CHEAP->EXPLICIT spectrum = the pragmatic encoding. THE SHARP PREDICTION: the
optimum SHIFTS with the quality of the SHARED MODEL. A listener with a RICHER model (trained on
MANY background alphabets) can invert a TERSER signal -> the speaker spends less. A POORER /
mismatched listener forces a MORE EXPLICIT signal. This is wife-vs-wide-audience, measured.

WHAT IS HELD / EARNED (donkey=0):
  * The SPECTRUM is generated by the agent's OWN trace machinery (abbreviate/reduce detail =
    resample to fewer arc-length points + drop the least-salient strokes). No borrowed data.
  * ProductionCost = the agent's OWN writer-physics EFFORT (integrated path length + integrated
    jerk = the minimum-jerk/two-thirds motor cost from earned_augmentation.motor_stats). NOT a
    hand-picked constant — the held motor-cost notion.
  * ListenerRecovery = the HELD listener's recovery score for the true class vs the 20-way
    distractor set (analysis_by_synthesis geometry + abs_learned_fusion learned channel).
  * THE SPEAKER'S ARGMAX DECISION = a HELD GRAPH TERM (Argmax over the spectrum of
    Plus([recovery, Times([Lit(-lambda), cost])]) — reuses the native_fusion Argmax-of-Plus
    machinery verbatim). Python is world-adapter glue: it renders the spectrum, asks the held
    listener for recovery, measures the held motor cost, writes them as graph attrs, evaluates
    the Term, reads back the chosen rendering. 0 LLM, 0 borrowed weights at decision time.

numpy USAGE (flagged): adapter math only — resampling/simplifying the trace, path-length/jerk
integration, cosine. The DECISION is the Rust Term.
"""
