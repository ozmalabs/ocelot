_L = lambda v: {"type": "Lit", "value": v}

# Per-rendering graph attrs the wrapper populates.
RECOVERY_ATTR = "recovery"   # held-listener recovery score for the true class (HIGHER = better)
COST_ATTR = "prod_cost"      # held writer-physics production effort (HIGHER = costlier)
RUNG_ATTR = "is_rung"        # spectrum-rung marker (== 1.0)
TERSE_ATTR = "terseness"     # the rung's terseness knob in [0,1] (read back at the argmax)


# --------------------------------------------------------------------------- #
#  THE CHEAP -> EXPLICIT SPECTRUM  (the agent's own abbreviate / reduce-detail knob)
# --------------------------------------------------------------------------- #

def simplify_strokes(strokes, terseness: float):
    """Render the target at a given TERSENESS (0 = full detail/explicit, 1 = cheapest/terse).
    The agent's OWN trace machinery: (a) resample each stroke to FEWER arc-length points as
    terseness rises (drop detail), and (b) at high terseness DROP the shortest strokes (abbreviate
    — omit the least-salient marks). No borrowed data; a pure simplification of the held trace."""
    strokes = [_np.asarray(s, float)[:, :2] for s in strokes if len(s) >= 1]
    if not strokes:
        return strokes
    # (a) DROP detail: keep a fraction of arc-length resolution (>=3 points to stay a stroke).
    keep_frac = 1.0 - 0.85 * float(terseness)          # 1.0 (full) -> 0.15 (terse)
    out = []
    # (b) ABBREVIATE: at high terseness, drop the shortest strokes (least information).
    lens = [float(_np.sqrt((_np.diff(s, axis=0) ** 2).sum(1)).sum()) if len(s) >= 2 else 0.0
            for s in strokes]
    order = _np.argsort(lens)                            # shortest first
    drop_n = int(round(0.6 * float(terseness) * len(strokes)))  # up to 60% of strokes at t=1
    drop_n = min(drop_n, len(strokes) - 1)               # always keep at least one stroke
    drop = set(order[:drop_n].tolist())
    for i, s in enumerate(strokes):
        if i in drop:
            continue
        n = len(s)
        if n < 3:
            out.append(s); continue
        k = max(3, int(round(keep_frac * n)))
        d = _np.sqrt((_np.diff(s, axis=0) ** 2).sum(1))
        cum = _np.concatenate([[0.0], _np.cumsum(d)])
        if cum[-1] == 0:
            out.append(s); continue
        u = _np.linspace(0.0, cum[-1], k)
        out.append(_np.stack([_np.interp(u, cum, s[:, 0]),
                              _np.interp(u, cum, s[:, 1])], 1))
    return out


def spectrum(strokes, n_rungs: int = 7):
    """The CHEAP->EXPLICIT spectrum: n_rungs renderings at terseness 0..1. Rung 0 = explicit
    (full detail), last rung = cheapest. Returns [(terseness, simplified_strokes), ...]."""
    ts = _np.linspace(0.0, 1.0, n_rungs)
    return [(float(t), simplify_strokes(strokes, t)) for t in ts]


# --------------------------------------------------------------------------- #
#  PRODUCTION COST  (the agent's OWN writer-physics effort — held motor cost, not a constant)
# --------------------------------------------------------------------------- #

def production_cost(strokes):
    """The thermodynamically-relevant PRODUCTION EFFORT of a rendering, in held writer-physics
    terms. A real hand pays for THREE things, all of which a terser/abbreviated rendering reduces:
      * PEN-DOWN travel  — distance the pen draws (drops as detail/wiggle is cut),
      * PEN-UP transit   — distance the hand moves BETWEEN strokes (drops as strokes are dropped:
                           more separate marks = more lift-and-reposition effort),
      * integrated JERK  — the minimum-jerk control cost the held writer-physics minimises
                           (earned_augmentation.motor_stats measures the same third-difference jerk).
    All three rise with detail; abbreviating (dropping marks) + reducing detail is genuinely
    CHEAPER. The held motor-cost notion, not a hand-picked constant. Scale-normalised by the
    figure extent so it measures SHAPE detail, not absolute pen size. numpy = effort integration."""
    strokes = [_np.asarray(s, float)[:, :2] for s in strokes if len(s) >= 2]
    if not strokes:
        return 0.0
    allp = _np.concatenate(strokes, axis=0)
    span = float(_np.abs(allp - allp.mean(0)).max()) + 1e-9
    pen_down = 0.0
    pen_up = 0.0
    jerk = 0.0
    prev_end = None
    for s in strokes:
        s = s / span
        d = _np.diff(s, axis=0)
        pen_down += float(_np.linalg.norm(d, axis=1).sum())
        if prev_end is not None:                # transit from the previous stroke's end (lift cost)
            pen_up += float(_np.linalg.norm(s[0] - prev_end))
        prev_end = s[-1]
        if len(s) >= 4:                         # third difference = jerk (held writer-physics cost)
            j = _np.diff(_np.diff(d, axis=0), axis=0)
            jerk += float(_np.linalg.norm(j, axis=1).sum())
    return pen_down + pen_up + jerk


# --------------------------------------------------------------------------- #
#  LISTENER RECOVERY  (the HELD listener inverts the rendered signal — the audience's model)
# --------------------------------------------------------------------------- #

def _strokes_point_set(strokes, N=80):
    """A rendering's normalized stroke POINT-SET (the same shape-space the held AbS listener
    inverts in). Mirrors analysis_by_synthesis.point_set but over in-memory strokes."""
    pts = []
    for st in strokes:
        st = _np.asarray(st, float)
        pts.extend([[float(p[0]), float(p[1])] for p in st])
    a = _np.asarray(pts, float)
    if len(a) < 3:
        return None
    a = a - a.mean(0)
    a = a / (_np.abs(a).max() + 1e-9)
    d = _np.sqrt((_np.diff(a, axis=0) ** 2).sum(1))
    cum = _np.concatenate([[0.0], _np.cumsum(d)])
    if cum[-1] == 0:
        return None
    u = _np.linspace(0.0, cum[-1], N)
    return _np.stack([_np.interp(u, cum, a[:, 0]), _np.interp(u, cum, a[:, 1])], 1).tolist()


def _softmax(x, temp=1.0):
    x = _np.asarray(x, float) / max(temp, 1e-9)
    x = x - x.max()
    e = _np.exp(x)
    return e / (e.sum() + 1e-12)


def geom_recovery(signal_strokes, support_point_sets, true_idx, temp=0.05):
    """The held GEOMETRY listener's RECOVERY probability of the true class for a rendering:
    softmax over the 20-way support set of the held AbS render-and-compare similarity (higher =
    the true class better explains the signal among the distractors). This IS the audience
    inverting the signal — analysis_by_synthesis.render_compare_score (held Terms), no learned
    feature. Returns P(true | signal) in [0,1]."""
    qps = _strokes_point_set(signal_strokes)
    if qps is None:
        return 0.0
    sims = _np.array([-_abs.render_compare_score(qps, s) for s in support_point_sets], float)
    return float(_softmax(sims, temp)[true_idx])


def learned_recovery(signal_strokes, embed_fn, support_embeds, true_idx, temp=0.05):
    """The held LEARNED listener channel's RECOVERY probability: softmax over the support set of
    the from-scratch learned head's cosine similarity. embed_fn embeds in-memory strokes (the
    learned head = the listener's DATA model, trained on N background alphabets = the SHARED-MODEL
    quality knob). Returns P(true | signal) in [0,1] (0.0 if the head cannot embed)."""
    qv = embed_fn(signal_strokes)
    if qv is None or any(e is None for e in support_embeds):
        return 0.0
    sims = _F.cos_sims(qv, support_embeds)
    return float(_softmax(sims, temp)[true_idx])


def fused_recovery(signal_strokes, support_point_sets, embed_fn, support_embeds, true_idx,
                   w_learn=1.0, temp=0.05):
    """The FULL held listener's recovery = average of the geometry and learned recovery (both
    held channels invert the signal; the listener's model quality lives in the learned channel's
    background size). If the learned head is absent, falls back to geometry alone."""
    g = geom_recovery(signal_strokes, support_point_sets, true_idx, temp)
    if embed_fn is None:
        return g
    l = learned_recovery(signal_strokes, embed_fn, support_embeds, true_idx, temp)
    return (g + w_learn * l) / (1.0 + w_learn)


def embed_strokes_fn(model, mu, sd):
    """An in-memory-strokes embedder for the learned listener channel (mirrors
    learned_perceptual_head.embed_scatter but over strokes, not a file path)."""
    import torch
    def _e(strokes):
        f = _sf.scatter_trace_image([_np.asarray(s, float)[:, :2] for s in strokes if len(s) >= 1])
        if f is None:
            return None
        with torch.no_grad():
            return model.embed(torch.tensor(((f - mu) / sd).astype(_np.float32))[None]).numpy()[0]
    return _e


# --------------------------------------------------------------------------- #
#  THE HELD SPEAKER DECISION TERM  (Argmax over the spectrum of the JOINT objective)
#  J(rung) = recovery[rung]  -  lambda * cost[rung]
#  = Argmax over rungs of Plus([ Attr(recovery), Times([Lit(-lambda), Attr(cost)]) ]).
#  Reuses native_fusion._Argmax / _Plus / _Times / _Attr / _NodesWhere / _V verbatim.
# --------------------------------------------------------------------------- #

def _rung_set():
    """The spectrum rung node set: every Concept with is_rung == 1 (one per terseness rung)."""
    return _nf._NodesWhere("Concept", RUNG_ATTR, _L(1.0))


def joint_score_term(lam: float) -> dict:
    """J(rung) = recovery[rung] - lambda * cost[rung] — a graph Plus of the audience-recovery
    term and the (negated, weighted) production-cost term. lambda is a Lit (the production-vs-
    decoding trade weight; a fixed/measured constant, not tuned against test). The held listener
    supplies recovery; the held writer-physics supplies cost."""
    return _nf._Plus([
        _nf._Attr(_nf._V("r"), RECOVERY_ATTR),                       # audience recovery (legibility)
        _nf._Times([_L(-float(lam)), _nf._Attr(_nf._V("r"), COST_ATTR)]),  # -lambda * production cost
    ])


def choose_term(lam: float) -> dict:
    """predict = Argmax over spectrum rungs of the joint objective — the WHOLE pragmatic-speaker
    decision as graph data (same Argmax-of-score shape native_fusion proved native)."""
    return _nf._Argmax(_rung_set(), "r", joint_score_term(lam))


# --------------------------------------------------------------------------- #
#  WORLD-ADAPTER GLUE: build the spectrum substrate, feed recovery + cost as attrs,
#  evaluate the held Term, read back the chosen rung's terseness. NO decision here.
# --------------------------------------------------------------------------- #

def choose_encoding(Substrate, Pred, terseness, recoveries, costs, lam: float):
    """Feed the spectrum's per-rung recovery + production-cost arrays as graph attrs, evaluate the
    held speaker Term, and return (chosen_terseness, chosen_index). The Term argmaxes the joint
    objective natively; Python only translates in/out. `terseness` / `recoveries` / `costs` are
    parallel arrays over the spectrum rungs."""
    s = Substrate()
    nodes = []
    for i in range(len(terseness)):
        nid = s.add_node("Concept", {"idx": float(i)})
        s.set_attr(nid, RUNG_ATTR, 1.0)
        s.set_attr(nid, TERSE_ATTR, float(terseness[i]))
        s.set_attr(nid, RECOVERY_ATTR, float(recoveries[i]))
        s.set_attr(nid, COST_ATTR, float(costs[i]))
        nodes.append(nid)
    pick = s.evaluate(Pred(choose_term(lam)), {})
    idx = int(round(s.node(pick)["attrs"]["idx"]))
    return float(terseness[idx]), idx


