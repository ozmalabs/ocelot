"""margin_world — the world-adapter surface for RUNG L1c (the DERIVED ADMISSION BOUND).

Mechanical I/O ONLY (PROTOCOL §0 / CLAUDE.md). This file contains exactly three
things: a BLIND WRITE of the instrument's flag; a BLIND INSTALL of each codebook
member's rounded self-renders plus the `has_codebook` edge that marks it as this
agent's pose codebook; and a READBACK of the `mg_*` attributes the seed rules wrote.
There is no conditional over graph state, no threshold, no comparison, no arithmetic
on a residual, and no decision.

WHAT IS AND IS NOT DELEGATED HERE — this is the load-bearing line for §0.

The adapter supplies the rounded self-renders as raw point sets. RENDERING IS
STIMULUS GENERATION — the same mechanical act, by the same `observe()` code path,
that produces every observation T1 is tested on; it is world I/O, not cognition.
**The DERIVATION is not here.** `eta_c = MAX over those renders of the residual` is
computed by the `mg_eta` SEED RULE, in the graph, from the agent's own `cp_angles`.
The adapter never computes a maximum, never compares a residual to anything, and
never sees a distance. Had the adapter computed `eta` numerically, the derivation
would have been made in Python and the rung would be void.

It is a SEPARATE file from `uniqueness_world` / the continuous-pose runner on
purpose: rung L1b's and rung T1's adapters belong to those rungs and are not this
rung's to edit (PROTOCOL §11.4).

Note what `verdict()` deliberately does NOT do: it does not combine T1's `status`
with a candidate count to derive an answer. That combination WOULD be a decision, and
it is made in the graph — `mg_admit` / `mg_ambiguous` / `mg_none` partition the
observations T1 claimed and write a single definitive `mg_status`. This function
reads that one attribute back.
"""
from __future__ import annotations


def set_flag(s, *, margin: float) -> None:
    """Blind-write the instrument flag on every MarginParams node. No read, no branch."""
    for p in s.nodes("MarginParams"):
        s.set_attr(p, "margin", float(margin))


def install_codebook(s, ag, selfviews: dict) -> None:
    """Blind-install, for each codebook member, its rounded self-renders (`mg_self`)
    and the `has_codebook` edge marking it as this agent's pose codebook.

    `selfviews` maps a ShapeSignature's `name` to a list of rendered point sets,
    generated by the caller's stimulus path. Mechanical translation only: this writes
    what it is given and reads nothing back.
    """
    by_name = {s.node(n)["attrs"].get("name"): n for n in s.nodes("ShapeSignature")}
    for nm, views in selfviews.items():
        n = by_name[nm]
        s.set_attr(n, "mg_self", views)
        s.add_edge(ag, "has_codebook", n)


def verdict(s, nid: int) -> dict:
    """The instrument's readback for one Observation (pure mechanical query).

    `mg_status` is written by the seed rules and is one of:
      * `mg_admitted`  — T1 claimed it AND exactly ONE candidate lay within its own
                         derived `eta`; `mg_covered_by` is T1's own Argmin winner,
                         term-for-term;
      * `mg_ambiguous` — T1 claimed it AND ≥2 candidates lay within their own `eta`,
                         so the instrument refused rather than let `Argmin` pick
                         silently;
      * `mg_none`      — T1 claimed it but NO candidate lay within its own `eta`;
      * `""` (absent)  — the instrument did not fire, because T1 itself never claimed
                         this observation (it refused, or the flag is off). Kept
                         DISTINGUISHABLE from an explicit refusal so "refused" and
                         "never ran" are never confused (§1.1's dead-arm lesson).

    `mg_ncand` is how many candidates were in contention — the ambiguity made into a
    POSITIVE datum rather than an absence.
    """
    a = s.node(nid)["attrs"]
    return {
        "mg_recognized": int(round(float(a.get("mg_recognized", 0.0)))),
        "mg_covered_by": a.get("mg_covered_by", ""),
        "mg_status": a.get("mg_status", ""),
        "mg_ncand": int(round(float(a.get("mg_ncand", 0.0)))),
    }


def eta_of(s, name: str) -> float:
    """Read back the `mg_eta` the SEED RULE derived for one codebook member.

    A pure readback of a graph attribute. The value is computed by `mg_eta` in the
    graph; this never recomputes it, and the `-1.0` absence marker is a sentinel, not
    a decision — it says "the rule has not run", which the caller reports as such.
    """
    by_name = {s.node(n)["attrs"].get("name"): n for n in s.nodes("ShapeSignature")}
    return float(s.node(by_name[name])["attrs"].get("mg_eta", -1.0))
