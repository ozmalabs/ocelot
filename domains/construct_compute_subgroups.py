_CONSTRUCTIBLE = {
    # the (first) Grigorchuk group — held in self_similar.GRIGORCHUK.
    "Grigorchuk group": {"recur": _ss.GRIGORCHUK, "gens": ["a", "b", "c", "d"]},
}


@dataclass
class Computed:
    group_name: str
    index: int
    value: Optional[int] = None
    method: str = ""
    hom_counts: dict = field(default_factory=dict)   # k -> h_k (stabilised)
    cross_check: Optional[int] = None                # the independent t_n/(n-1)! value
    depth_used: int = 0
    detail: str = ""
    constructed: bool = False


# ---------------------------------------------------------------------------
# CONSTRUCT — the finite quotient G_m as permutations of the 2^m leaves, by ACTING
# the held generators (self_similar.act). No presentation; pure construction.
# ---------------------------------------------------------------------------

def _gen_perms(recur, gens, m):
    """The generator permutations of G_m = G/Stab(level m): act each held generator
    on every length-m leaf. Mechanical construction via the held tree action."""
    leaves = list(product((0, 1), repeat=m))
    idx = {leaf: i for i, leaf in enumerate(leaves)}
    out = []
    for g in gens:
        p = [0] * len(leaves)
        for leaf in leaves:
            p[idx[leaf]] = idx[_ss.act(g, leaf, recur)]
        out.append(tuple(p))
    return out


def _comp(p, q):
    """Permutation composition (p after q): (p∘q)[i] = p[q[i]]."""
    return tuple(p[q[i]] for i in range(len(p)))


def _ident(n):
    return tuple(range(n))


def _group_order(gen_perms):
    """|G_m|: the closure of the generator permutations (BFS over the Cayley graph)."""
    n = len(gen_perms[0])
    i0 = _ident(n)
    seen = {i0}
    frontier = [i0]
    while frontier:
        nf = []
        for x in frontier:
            for g in gen_perms:
                y = _comp(x, g)
                if y not in seen:
                    seen.add(y)
                    nf.append(y)
        frontier = nf
    return len(seen)


# ---------------------------------------------------------------------------
# ENUMERATE — |Hom(G_m, S_k)|. A generator-image tuple defines a homomorphism iff
# the graph subgroup of G_m × S_k it generates projects ISOMORPHICALLY onto G_m
# (a function, total, well-defined). The exact test, no relator harvesting.
# ---------------------------------------------------------------------------

def _extends_to_hom(gen_perms, imgs, order_Gm):
    """Does the assignment gen_i -> imgs_i extend to a homomorphism G_m -> S_k?
    Exact: build the graph subgroup of G_m × S_k; it is a valid hom iff the map is a
    well-defined function on all of G_m (closure size = |G_m|, no conflicting image)."""
    nG = len(gen_perms[0])
    iG = _ident(nG)
    k = len(imgs[0])
    iK = _ident(k)
    funcmap = {iG: iK}
    frontier = [(iG, iK)]
    pairs = list(zip(gen_perms, imgs))
    ok = True
    while frontier and ok:
        nf = []
        for (x, y) in frontier:
            for (gx, gy) in pairs:
                nx = _comp(x, gx)
                ny = _comp(y, gy)
                if nx in funcmap:
                    if funcmap[nx] != ny:
                        ok = False
                        break
                else:
                    funcmap[nx] = ny
                    nf.append((nx, ny))
            if not ok:
                break
        frontier = nf
    return ok and len(funcmap) == order_Gm


def _candidate_images(k):
    """Generate candidate (A,B,C,D) image tuples for the Grigorchuk generators in S_k,
    using ONLY the generators' OWN order/commuting structure (a,b,c,d involutions;
    {1,b,c,d} a Klein 4-group, so b,c commute and d=bc). This is a property of the
    GENERATORS (their held sections square to identity, bc=d), not of the answer — it
    prunes the S_k^4 enumeration to the admissible tuples the full quotient test then
    confirms. The structure is read off the held recursion, never the key."""
    iK = _ident(k)
    invol = [p for p in permutations(range(k)) if _comp(p, p) == iK]  # order | 2
    for A in invol:
        for B in invol:
            for C in invol:
                if _comp(B, C) != _comp(C, B):    # [b,c] = 1
                    continue
                D = _comp(B, C)                    # d = bc
                if _comp(D, D) != iK:              # d^2 = 1
                    continue
                yield (A, B, C, D)


def _hom_count(gen_perms, k, order_Gm):
    """|Hom(G_m, S_k)|: count admissible image tuples that extend to a homomorphism."""
    return sum(1 for imgs in _candidate_images(k)
               if _extends_to_hom(gen_perms, imgs, order_Gm))


def _transitive_hom_count(gen_perms, k, order_Gm):
    """#TRANSITIVE homomorphisms G_m -> S_k (the image acts transitively on k points)
    — the independent count for the cross-check a_n = t_n/(n-1)!."""
    t = 0
    for imgs in _candidate_images(k):
        if not _extends_to_hom(gen_perms, imgs, order_Gm):
            continue
        # transitive iff the orbit of point 0 under the generator images is all k points
        seen = {0}
        frontier = [0]
        while frontier:
            nf = []
            for x in frontier:
                for p in imgs:
                    y = p[x]
                    if y not in seen:
                        seen.add(y)
                        nf.append(y)
            frontier = nf
        if len(seen) == k:
            t += 1
    return t


def _stable_hom_counts(recur, gens, n, max_depth=5):
    """Compute h_k = |Hom(G, S_k)| for k = 1..n by constructing G_m at increasing depth
    until the WHOLE vector (h_1..h_n) is unchanged across two consecutive depths. Since
    every hom factors through some finite quotient and the counts are bounded by (k!)^4,
    this stabilises; the stable vector is |Hom(G, S_k)| for the infinite group. Returns
    (h dict, transitive dict t_k, depth_used) or (None, None, depth) on no stabilisation."""
    prev = None
    prev_t = None
    for m in range(2, max_depth + 1):
        gp = _gen_perms(recur, gens, m)
        order_Gm = _group_order(gp)
        h = {k: _hom_count(gp, k, order_Gm) for k in range(1, n + 1)}
        t = {k: _transitive_hom_count(gp, k, order_Gm) for k in range(1, n + 1)}
        if prev is not None and h == prev and t == prev_t:
            return h, t, m
        prev = h
        prev_t = t
    return None, None, max_depth


# ---------------------------------------------------------------------------
# COMPUTE — the Hall recursion over the held arithmetic (reason.solve), exact through
# the fractional intermediate terms. a_n = h_n/(n-1)! - sum_{v<n} h_{n-v}/(n-v)! a_v.
# ---------------------------------------------------------------------------

def _hall_recursion(h, n):
    """a_n via the Hall identity over HELD arithmetic. Every step is reason.solve
    (div/factorial/times/minus); the intermediate a_v stay exact Fractions, a_n integral."""
    a = {}
    for k in range(1, n + 1):
        # lead = h_k / (k-1)!
        fact = _reason.solve({"factorial": {"of": k - 1}}, {})
        val = _reason.solve({"div": {"left": h[k], "right": fact}}, {})
        for v in range(1, k):
            fv = _reason.solve({"factorial": {"of": k - v}}, {})
            quot = _reason.solve({"div": {"left": h[k - v], "right": fv}}, {})
            term = _reason.solve({"times": {"left": quot, "right": a[v]}}, {})
            val = _reason.solve({"minus": {"left": val, "right": term}}, {})
        a[k] = val
    return a


# ===========================================================================
# THE ROUTE — construct -> enumerate -> compute -> cross-check. General (registry
# keyed on the recognised name); no answer, no per-QID branch.
# ===========================================================================

def can_construct(group_name: str) -> bool:
    """Is the named group's action HELD (constructible over the held primitives)?"""
    return group_name in _CONSTRUCTIBLE


def compute_subgroup_count(group_name: str, index: int) -> Computed:
    """CONSTRUCT the named group's action over held primitives, ENUMERATE Hom(G,S_k) to
    stability, COMPUTE the index-`index` subgroup count via the Hall recursion, and
    CROSS-CHECK it against the independent transitive-action count. Returns a Computed
    carrying the value (None if the construction is not held, the counts do not
    stabilise, or the two independent computations disagree). The KEY is never read."""
    out = Computed(group_name=group_name, index=index)
    spec = _CONSTRUCTIBLE.get(group_name)
    if spec is None:
        out.detail = (f"{group_name}: no held wreath recursion -> not constructible "
                      f"(the construction is the marginal cost, honestly absent here)")
        return out
    out.constructed = True
    n = index
    h, t, depth = _stable_hom_counts(spec["recur"], spec["gens"], n)
    out.depth_used = depth
    if h is None:
        out.detail = (f"{group_name}: Hom(G,S_k) counts did not stabilise by depth "
                      f"{depth} -> no value (enumeration-tractability stall)")
        return out
    out.hom_counts = dict(h)

    # COMPUTE a_n via the Hall recursion (held arithmetic).
    a = _hall_recursion(h, n)
    a_n = a[n]
    if a_n != int(a_n):
        out.detail = (f"{group_name}: Hall recursion gave non-integer {a_n} "
                      f"(stabilisation incomplete) -> no value")
        return out
    a_n = int(a_n)

    # CROSS-CHECK (shared guard): a_n = t_n / (n-1)!  (an INDEPENDENT transitive-action
    # identity, no Hall recursion). The Hall a_n and this count must AGREE, else the value
    # is unconfirmed and withheld -> a NAMED honest miss.
    fact = _reason.solve({"factorial": {"of": n - 1}}, {})
    cc = _reason.solve({"div": {"left": t[n], "right": fact}}, {})
    out.cross_check = int(cc) if cc == int(cc) else cc

    stall = _certify.guard(out, group_name, [
        _certify.Check(f"Hall a_{n} == independent transitive t_{n}/(n-1)!",
                       a_n, out.cross_check),
    ])
    if stall is not None:
        return stall

    out.value = a_n
    out.method = "construct(tree action) -> enumerate Hom(G,S_k) -> Hall recursion"
    out.detail = (f"#index-{n} subgroups of {group_name} = {a_n}: constructed G_m on "
                  f"2^{depth} leaves (held wreath recursion), enumerated h_k={dict(h)} "
                  f"(stable at depth {depth}), Hall recursion over held arithmetic; "
                  f"independent cross-check t_{n}/(n-1)! = {out.cross_check} AGREES")
    return out


