#!/usr/bin/env python3
"""Generate and validate the formal-paper version include.

paper_metadata.json is the sole editable source of paper draft identity and
per-paper revisions. This script renders the committed paper_metadata.tex include
used by LaTeX. Keeping the generated include in the tree makes direct pdflatex
builds reproducible while --check prevents the artifact from drifting.

Usage:
    python3 tools/build_paper_metadata.py
    python3 tools/build_paper_metadata.py --check
    python3 tools/build_paper_metadata.py --migrate
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FORMAL = ROOT / "papers" / "formal"
MANIFEST = FORMAL / "paper_metadata.json"
INCLUDE = FORMAL / "paper_metadata.tex"
DRAFT_RE = re.compile(r"draft-\d{4}-\d{2}-\d{2}(?:\.\d+)?")
DATE_RE = re.compile(
    r"\b\d{1,2} (?:January|February|March|April|May|June|July|August|"
    r"September|October|November|December) \d{4}\b"
)
REV_RE = re.compile(r"document revision \d+")
REV_TOKEN_RE = re.compile(r"\br\d+\b")


def load_manifest(path=MANIFEST):
    data = json.loads(path.read_text(encoding="utf-8"))
    if not DRAFT_RE.fullmatch(data.get("draft", "")):
        raise ValueError("manifest draft must be draft-YYYY-MM-DD.N")
    if not DATE_RE.fullmatch(data.get("display_date", "")):
        raise ValueError("manifest display_date must be e.g. '6 September 2026'")
    papers = data.get("papers")
    if not isinstance(papers, dict) or not papers:
        raise ValueError("manifest requires a non-empty papers object")
    for stem, entry in papers.items():
        if not isinstance(entry, dict):
            raise ValueError("%s metadata must be an object" % stem)
        if "revision" in entry:
            if not isinstance(entry["revision"], int) or entry["revision"] < 1:
                raise ValueError("%s revision must be a positive integer" % stem)
        elif "generated_from" in entry:
            parent = entry["generated_from"]
            if parent not in papers or "revision" not in papers[parent]:
                raise ValueError("%s generated_from must name a revisioned paper" % stem)
        else:
            raise ValueError("%s needs revision or generated_from" % stem)
    return data


def revision_for(data, stem):
    entry = data["papers"][stem]
    if "revision" in entry:
        return entry["revision"]
    return revision_for(data, entry["generated_from"])


def render(data):
    lines = [
        "% GENERATED by tools/build_paper_metadata.py from paper_metadata.json.",
        "% DO NOT EDIT: edit paper_metadata.json, then regenerate this file.",
        r"\providecommand{\PaperDraft}{%s}" % data["draft"],
        r"\providecommand{\PaperDisplayDate}{%s}" % data["display_date"],
    ]
    for stem in sorted(data["papers"]):
        lines.append(r"\expandafter\def\csname PaperRevision@%s\endcsname{%s}" %
                     (stem, revision_for(data, stem)))
    for stem, entry in sorted(data["papers"].items()):
        if "generated_from" in entry:
            lines.append(r"\expandafter\def\csname PaperGenerated@%s\endcsname{1}" % stem)
    lines.extend([
        r"\edef\PaperMetadataStem{\jobname}",
        r"\expandafter\ifx\csname PaperRevision@\PaperMetadataStem\endcsname\relax",
        r"  \PackageError{paper_metadata}{No metadata for \PaperMetadataStem}{Add the paper stem to paper_metadata.json.}",
        r"  \def\PaperRevision{?}",
        r"\else",
        r"  \expandafter\let\expandafter\PaperRevision\csname PaperRevision@\PaperMetadataStem\endcsname",
        r"\fi",
        r"\newcommand{\PaperDateLine}{\textbf{Draft \texorpdfstring{\textemdash}{---}\ \PaperDraft}\\[2pt]\PaperDisplayDate\ \texorpdfstring{\textbullet}{\textperiodcentered}\ document revision \PaperRevision}",
        r"\newcommand{\PaperStatementDateLine}{\textbf{Draft \texorpdfstring{\textemdash}{---}\ \PaperDraft}\\[2pt]\PaperDisplayDate\ \texorpdfstring{\textbullet}{\textperiodcentered}\ statement}",
        r"\expandafter\ifx\csname PaperGenerated@\PaperMetadataStem\endcsname\relax",
        r"  \newcommand{\PaperFooterStamp}{\textsc{\PaperDraft\,r\PaperRevision}}",
        r"\else",
        r"  \newcommand{\PaperFooterStamp}{\textsc{\PaperDraft\ / statement / from long r\PaperRevision}}",
        r"\fi",
        r"\newcommand{\PaperNoticeStamp}{\textbf{DRAFT --- \PaperDraft\ r\PaperRevision} (\PaperDisplayDate).}",
        "",
    ])
    return "\n".join(lines)


def migrate(data):
    """Replace only version metadata in formal sources with generated macros."""
    changed = []
    for stem, entry in data["papers"].items():
        if "generated_from" in entry:
            continue
        path = FORMAL / (stem + ".tex")
        if not path.exists():
            raise ValueError("manifest source missing: %s" % path)
        text = path.read_text(encoding="utf-8")
        new = DRAFT_RE.sub(r"\\PaperDraft", text)
        new = DATE_RE.sub(r"\\PaperDisplayDate", new)
        new = REV_RE.sub(r"document revision \\PaperRevision", new)
        new = REV_TOKEN_RE.sub(r"r\\PaperRevision", new)
        if r"\input{paper_metadata.tex}" not in new:
            new = new.replace(r"\begin{document}",
                              "\\input{paper_metadata.tex}\n\n\\begin{document}", 1)
        if new != text:
            path.write_text(new, encoding="utf-8")
            changed.append(path.name)

    spec = FORMAL / "01s.spec"
    text = spec.read_text(encoding="utf-8")
    new = DRAFT_RE.sub(r"\\PaperDraft", text)
    new = DATE_RE.sub(r"\\PaperDisplayDate", new)
    new = re.sub(r"\\date\{.*", r"\\date{\\PaperStatementDateLine}", new)
    if new != text:
        spec.write_text(new, encoding="utf-8")
        changed.append(spec.name)
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if generated include is stale")
    ap.add_argument("--migrate", action="store_true", help="replace handwritten formal-source metadata")
    args = ap.parse_args()
    try:
        data = load_manifest()
        expected = render(data)
        if args.migrate:
            changed = migrate(data)
            print("migrated %d source file(s)" % len(changed))
        if args.check:
            if not INCLUDE.exists() or INCLUDE.read_text(encoding="utf-8") != expected:
                raise ValueError("paper_metadata.tex is missing or stale; run tools/build_paper_metadata.py")
        else:
            INCLUDE.write_text(expected, encoding="utf-8")
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print("paper metadata: %s" % exc, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
