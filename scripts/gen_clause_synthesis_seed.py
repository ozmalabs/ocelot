"""Generator for seeds/clause_synthesis.json — NOVEL clause synthesis (extension a), pure graph data.

The jabberwock's design, realised without new Rust: a clause is just a Term-JSON value, and the DSL already
has `MkDict` (build a Value::Dict at evaluate time) + `Vec` (build a Tuple). So a parameterised ClauseTemplate
is a Term that CONSTRUCTS the clause-dict and SPLICES live fault operands via `Attr(f, ...)`. When a synth
Fault is open (awaiting_synth>0.5) and its shape matches a template, `synthesize_<shape>` builds the corrected
clause from the fault's live operands and clears awaiting_synth; the existing repair_apply then installs it.

Demonstrated shape `threshold_gate`: the fix is a `where` clause Gt(Attr(<gate_var>, <gate_attr>), <good_thresh>)
— every leaf a LIVE operand read off the Fault, so two faults with different operands synthesise DIFFERENT
clauses (genuinely novel, not a stored copy). No cloning, no Rust, no rebuild.

Run: python3 scripts/gen_clause_synthesis_seed.py
"""
from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def V(n): return {"type": "Var", "name": n}
def Lit(v): return {"type": "Lit", "value": v}
def Attr(node, k): return {"type": "Attr", "node": node, "key": k}
def P0(var, k): return {"type": "Plus", "items": [Attr(V(var), k), Lit(0.0)]}
def And(items): return {"type": "And", "items": items}
def Eq(a, b): return {"type": "Eq", "a": a, "b": b}
def Gt(a, b): return {"type": "Gt", "a": a, "b": b}
def Lt(a, b): return {"type": "Lt", "a": a, "b": b}


def mkd(pairs):
    """Build a Value::Dict (a Term-JSON node) at evaluate time. pairs = [(key_str, value_term), ...]."""
    items = []
    for k, v in pairs:
        items += [Lit(k), v]
    return {"type": "MkDict", "items": items}


def threshold_gate_where():
    """Synthesise the WHERE clause Gt(Attr(<gate_var>, <gate_attr>), Lit(<good_thresh>)) from LIVE fault
    operands — each leaf is Attr(f, ...), so the constructed clause differs per fault. This IS the template;
    its 'holes' are the Attr(f, ...) reads, bound at synthesis time."""
    f = V("f")
    return mkd([
        ("type", Lit("Gt")),
        ("a", mkd([
            ("type", Lit("Attr")),
            ("node", mkd([("type", Lit("Var")), ("name", Attr(f, "gate_var"))])),
            ("key", Attr(f, "gate_attr")),
        ])),
        ("b", mkd([("type", Lit("Lit")), ("value", Attr(f, "good_thresh"))])),
    ])


def synth_rule():
    return {
        "name": "synthesize_threshold_gate",
        "comment": "NOVEL clause synthesis: for an open synth Fault (awaiting_synth>0.5) of shape "
                   "threshold_gate, BUILD the corrected where clause from the fault's live operands "
                   "(gate_var/gate_attr/good_thresh) via MkDict, set f.corrected, and clear awaiting_synth so "
                   "repair_apply installs it. Two faults with different operands -> different clauses. Pure "
                   "graph data; no stored clause copied.",
        "match": [["a", "has_fault", "f"]],
        "where": And([
            Gt(P0("f", "awaiting_synth"), Lit(0.5)),
            Eq(Attr(V("f"), "shape"), Lit("threshold_gate")),
        ]),
        "effects": [
            ["set_attr", "f", "corrected", {"__term__": threshold_gate_where()}],
            ["set_attr", "f", "awaiting_synth", 0.0],
        ],
    }


def main():
    seed = {
        "id": "clause_synthesis",
        "version": "1.0.0",
        "depends_on": ["self_repair"],
        "description": "NOVEL clause synthesis (extension a): build a repair clause from a parameterised "
                       "ClauseTemplate by splicing the fault's LIVE operands via MkDict — pure graph data, no "
                       "Rust. Lets the agent fix faults it has no exact stored clause for. Generated by "
                       "scripts/gen_clause_synthesis_seed.py.",
        "microtheory": {"name": "clause_synthesis",
                        "description": "synthesise a repair clause from live operands; novel, not a stored copy"},
        "nodes": [], "edges": [], "productions": [],
        "rules": [synth_rule()],
    }
    out = os.path.join(ROOT, "seeds", "clause_synthesis.json")
    tmp = out + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(seed, fh, indent=1)
    json.load(open(tmp))
    os.replace(tmp, out)
    print(f"wrote + validated {os.path.relpath(out, ROOT)} ({len(seed['rules'])} rules)")


if __name__ == "__main__":
    main()
