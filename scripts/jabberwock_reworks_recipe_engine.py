def rework_extractor(reader: GraphReader, diag: dict) -> dict:
    skeleton_keys = diag["gap2_extractor_skeleton_keys"]
    # the agent's OWN vocabulary for "a quantity indexed over a structured family", read
    # from the euler/f-vector machinery it holds (per-dimension, over each i in 0..d, the
    # f-vector, the alternating sum over levels). These are the structural markers of the
    # shape-class the 12 lack — the SOURCE of evidence/triggers is the agent's f-vector.
    family_markers = [
        r"\bmax(?:imum)?\b[^.]{0,40}\b(?:over|of|dimension|degree|index|simplex)",
        r"\bhighest\b[^.]{0,40}\b(?:dimension|degree|index|level)",
        r"\bextremum\b", r"\bsupremum\b",
        r"\bover\s+(?:each|all|every)\s+\w+",
        r"\bfor\s+each\s+(?:dimension|level|index|degree)\b",
        r"\bindexed\s+(?:family|by)\b", r"\bf-?vector\b",
        r"\bsum\s+over\b", r"\brange\s+of\s+\w+",
    ]
    new_extractor = {}
    for k in skeleton_keys:
        if k == "id":
            new_extractor[k] = "reduce_over_structured_family"
        elif k == "evidence":
            new_extractor[k] = list(family_markers)
        elif k == "triggers":
            new_extractor[k] = [
                r"\bmax(?:imum)?\b[^.]{0,40}\b(?:dimension|degree|index|simplex|level)",
                r"\bhighest\b[^.]{0,40}\b(?:dimension|degree|index|level)",
                r"\bextremum\b[^.]{0,40}\bfamily\b",
                r"\bover\s+(?:each|all)\s+(?:dimension|level|index|degree)",
                # the DERIVED step (so order-1 -> order-2 can chain):
                r"\bcount\b[^.]{0,40}\b(?:occupied|nonempty|present|nonzero)\s+level",
                r"\breduce\b[^.]{0,40}\bfamily\b",
            ]
        elif k == "consequence":
            new_extractor[k] = (
                "an EXTREMUM / max / sum of a quantity over a STRUCTURED, INDEXED "
                "FAMILY (cf. {src}) is a REDUCE over the family's index range: the "
                "extremum need not be read off the unbounded object — iterate the index "
                "over its range and REDUCE the per-index quantity by STRUCTURE (count "
                "the occupied / non-empty levels, or sum/extreme over the range), so a "
                "max-over-a-collection becomes a count/sum over a held range")
        elif k == "match_keys":
            new_extractor[k] = ["reduce", "range", "count", "occupied", "extremum"]
        elif k == "name_signals":
            new_extractor[k] = [r"\bdimension\b", r"\bmax\b", r"\brange\b",
                                r"\breduce\b", r"\bcount\b", r"f.?vector"]
        elif k == "name_keys_for":
            # the capability the consequence names (the SELECTOR's coverage tokens).
            new_extractor[k] = ["dimension-as-count-of-occupied-levels",
                                "reduce-over-range", "max-as-count-minus-one"]
        else:
            new_extractor[k] = None
    return new_extractor


