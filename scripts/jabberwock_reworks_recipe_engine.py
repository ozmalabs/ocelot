# (3c) REWORK — THE BRIDGE, by abstracting the agent's OWN euler recipe AST and
# TRANSFERRING its per-level reduction to the new shape-class, EMITTING a recipe STRING.
#
# The agent's OWN euler recipe (compute_reduced_euler / the DEFS in
# jabberwock_self_generates_downstream) is:
#     euler(complex, d) = sum{ i in 0..d : neg_one_pow(i) *
#                              cardinality(simplices_of_dim(complex, i)) }
# Its meaning-Term (comprehend) is the SKELETON we abstract:
#     sum_where( source=range_incl(0..BOUND), var=V,
#                value = times( neg_one_pow(V),
#                               cardinality(simplices_of_dim(complex, V)) ) )
# The TRANSFER for the reduce-over-structured-family shape-class:
#   · KEEP the sum_where / range_incl(0..BOUND) / cardinality(simplices_of_dim(complex,V))
#     SKELETON (read off the euler recipe — the agent's own per-level face-count);
#   · REPLACE the per-level reduction  times(neg_one_pow(V), ·)  (alternating-sign WEIGHT)
#     with  ge(·, 1)  (the NON-EMPTY INDICATOR — "level V is occupied");
#   · OFFSET by  minus(·, 1)  (an extremum-INDEX is the count of occupied levels minus
#     one, because the occupied levels of a complex are contiguous 0..top).
# The emitter renders the transferred meaning-Term back to the compute_grounding RECIPE
# STRING surface (the `sum{ V in LO..HI : BODY } - 1` register comprehend parses).
# ===========================================================================

def _read_euler_skeleton() -> dict:
    """Read the agent's OWN euler recipe -> its meaning-Term (the comprehend AST). The
    recipe STRING is the agent's held derivation (compute_reduced_euler's chi-tilde
    f-vector / the downstream DEFS). Returns the meaning-Term skeleton."""
    euler = ("euler(complex, d) = sum{ i in 0..d : neg_one_pow(i) * "
             "cardinality(simplices_of_dim(complex, i)) }")
    comp = cg.comprehend_computational_definition(euler)
    return comp["term"], euler


def _emit_recipe_string(term: dict, head: str, params: list) -> str:
    """MECHANICAL emit-back: render a transferred meaning-Term to the compute_grounding
    recipe STRING surface (the inverse of comprehend's parse — a fixed Term-type ->
    surface map). Only the Term-types the transfer produces are handled; anything else
    raises (the named residual). NO math decided here — a surface renderer."""
    def r(t) -> str:
        if isinstance(t, str):
            return t
        if isinstance(t, (int, float)):
            return str(t)
        h = next(k for k in t if k != "force")
        a = t[h]
        if h == "sum_where":
            src = a["source"]["range_incl"]
            return (f"sum{{ {a['var']} in {r(src['lo'])}..{r(src['hi'])} : "
                    f"{r(a['value'])} }}")
        if h == "range_incl":
            return f"{r(a['lo'])}..{r(a['hi'])}"
        if h == "ge":
            return f"{r(a['left'])} >= {r(a['right'])}"
        if h == "minus":
            return f"{r(a['left'])} - {r(a['right'])}"
        if h == "times":
            return f"{r(a['left'])} * {r(a['right'])}"
        if h == "cardinality":
            return f"cardinality({r(a['of'])})"
        if h == "simplices_of_dim":
            return f"simplices_of_dim({r(a['complex'])}, {r(a['k'])})"
        if h == "neg_one_pow":
            return f"neg_one_pow({r(a['i'])})"
        raise ValueError(f"recipe emitter has no surface for Term-type {h!r} "
                         f"(the named residual)")
    rhs = r(term)
    return f"{head}({', '.join(params)}) = {rhs}"


def rework_bridge() -> dict:
    """ABSTRACT the agent's euler recipe AST + TRANSFER the per-level reduction to the
    reduce-over-structured-family shape-class, EMIT the recipe STRING. Returns the
    provenance + the emitted dimension recipe string."""
    euler_term, euler_str = _read_euler_skeleton()
    # ---- ABSTRACT: confirm the euler skeleton shape (sum_where over range of a per-level
    #      reduction of cardinality(simplices_of_dim(complex, VAR))) — read off the term.
    sw = euler_term["sum_where"]
    var = sw["var"]
    src = sw["source"]["range_incl"]
    body = sw["value"]                          # times(neg_one_pow, cardinality(...))
    # the per-level LEAF (the agent's own face-count) — the part the transfer KEEPS.
    # In euler it is the `right` of the times; we locate the cardinality(simplices_of_dim)
    # leaf structurally (the part NOT the sign weight).
    def find_card(t):
        if isinstance(t, dict):
            if "cardinality" in t:
                return t
            for v in t.values():
                if isinstance(v, dict):
                    f = find_card(v)
                    if f is not None:
                        return f
        return None
    leaf = find_card(body)
    assert leaf is not None, "euler skeleton: no cardinality(simplices_of_dim) leaf"

    # ---- TRANSFER: rebind the leaf's index var to the new var 'k' and the complex 'complex'
    #      (mechanical substitution); replace the per-level reduction (times-with-sign) by
    #      the NON-EMPTY INDICATOR ge(leaf, 1); offset the whole sum by minus(., 1).
    new_var = "k"
    new_bound = "N"
    # rebind the leaf's index (euler's VAR -> new_var) by mechanical substitution.
    def subst(t, old, new):
        if t == old:
            return new
        if isinstance(t, dict):
            return {h: {r2: subst(c, old, new) for r2, c in t[h].items()} for h in t}
        return t
    leaf_rebound = subst(leaf, var, new_var)
    # the TRANSFERRED meaning-Term: minus( sum_where( range_incl(0..N), k,
    #   ge( cardinality(simplices_of_dim(complex,k)), 1 ) ), 1 )
    transferred = {
        "minus": {
            "left": {"sum_where": {
                "source": {"range_incl": {"lo": 0, "hi": new_bound}},
                "var": new_var,
                "value": {"ge": {"left": leaf_rebound, "right": 1}},
            }},
            "right": 1,
        }
    }
    recipe = _emit_recipe_string(transferred, "dimension", ["complex", new_bound])
    return {
        "transfer_source_recipe": euler_str,
        "abstracted_skeleton": "sum_where(range_incl(0..BOUND), V, "
                               "<per-level reduction of cardinality(simplices_of_dim("
                               "complex,V))>)",
        "transfer": ("KEEP sum_where/range_incl/cardinality(simplices_of_dim) leaf; "
                     "REPLACE per-level reduction times(neg_one_pow(V),.) [sign WEIGHT] "
                     "-> ge(.,1) [non-empty INDICATOR]; OFFSET minus(.,1) [extremum-index "
                     "= count of occupied contiguous levels minus one]"),
        "transferred_meaning_term": transferred,
        "emitted_recipe_string": recipe,
    }


