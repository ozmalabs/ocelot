def _harvest_on_loaded_agent(harvest_fix) -> list:
    """Boot a substrate with the agent's concepts + their Term-trees, then run the
    reworked harvest-fix closure over it. The agent's Term-treed concepts are registered
    at the WORLD-ADAPTER boundary the harvester ships (harvester_shape.register_postulate
    _term) — the legitimate path a concept-with-a-Term-tree enters the catalogue. We
    register the agent's OWN grounded compute recipes (held in compute_grounding's
    relational templates + the held f-vector / euler / dimension family) so the reworked
    walk harvests SEVERAL shapes — vs the stub's unconditional 0. Best-effort: any seed
    breadth present is also walked."""
    from substrate_rs import Substrate
    from domains import harvester_shape as _hs
    sub = Substrate()
    # the agent's OWN Term-treed concepts, in the DSL Term-JSON format shape_of_term
    # consumes (the format the shipped BOOTSTRAP_CONCEPTS / promotion registries carry —
    # NOT the reason.solve meaning-Term format, a distinction lookup_postulate_term
    # honours). We add each shipped bootstrap concept as a Concept node so the reworked
    # walk fetches its Term-tree via the shipped lookup and runs shape_of_term — vs the
    # stub's unconditional 0.
    n_seeded = 0
    try:
        from domains.text_concept_bootstrap import BOOTSTRAP_CONCEPTS
        for nm, _t in BOOTSTRAP_CONCEPTS:
            sub.add_node("Concept", {"name": nm})
            n_seeded += 1
    except Exception:
        pass
    # also register a held DSL-format compute Term-tree at the shipped world-adapter
    # boundary (register_postulate_term) — e.g. eigenvalues, which shape_of_term shapes
    # at order_n=2 — proving the walk harvests registered-at-boundary concepts too.
    try:
        from domains import mathematics as _m
        install = getattr(_m, "install_mathematics_seed", None)
        if install is not None:
            install(sub)            # registers grounded math Term-trees + concepts
            n_seeded += 1
    except Exception:
        pass
    return harvest_fix(sub)


def _persist(s, recipe: str) -> dict:
    """Persist the invented faculty via the agent's OWN persist-on-wire loop, gated by the
    self-verify, then RELOAD it (install_self_authored re-grounds + re-computes) to prove
    durability. Writes to a TEMP dir (no repo seed mutation — the committed dimension.json
    is the reviewer's, untouched)."""
    import tempfile
    from pathlib import Path
    from domains import self_authored as sa
    tmp = Path(tempfile.mkdtemp(prefix="rework_dim_"))
    knowns = load_known_values()
    caps = dict(reason.CAPABILITIES)
    wp = sa.wire_and_persist_composition(s, "dimension", recipe, caps,
                                         knowns=knowns, directory=tmp)
    out = {"persisted": wp["persisted"], "reload_ok": False, "path": wp["path"]}
    if not wp["persisted"]:
        return out
    # RELOAD on a fresh substrate + fresh caps; re-ground from the manifest; re-compute.
    from substrate_rs import _native as _n
    s2 = _n.Substrate()
    gr.open_grounding_productions(s2)
    caps2 = dict(reason.CAPABILITIES)
    installed = sa.install_self_authored(s2, capabilities=caps2, directory=tmp)
    if "dimension" in installed:
        ok = True
        for arg, expected in knowns:
            try:
                got = reason.solve({"dimension": dict(arg)}, {}, capabilities=caps2)
                ok = ok and (int(got) == int(expected))
            except Exception:
                ok = False
        out["reload_ok"] = ok
    return out


