def diagnose(reader: GraphReader, recs: dict) -> dict:
    diag = {}
    # GAP 1 — the STUB: a `Pass` AstNode inside harvest_shape_donors' concept-walk loop.
    # Find harvest_shape_donors' func root, its `for c in substrate.nodes("Concept")`
    # loop, whose body's try contains the literal `pass`.
    hs_mod = recs["harvester_shape"]["module"]
    hsd_root = recs["harvester_shape"]["func_roots"]["harvest_shape_donors"]
    passes = []
    for p in reader.nodes_of_type("Pass", hs_mod):
        passes.append(p)
    diag["gap1_stub_pass_nodes"] = passes
    diag["gap1_harvest_func_root"] = hsd_root

    # GAP 2 — the 12 EXTRACTORS: the List of Dict literals returned by _extractors().
    ex_mod = recs["implication_harvester"]["module"]
    ex_root = recs["implication_harvester"]["func_roots"]["_extractors"]
    ret = next(b for b in reader.func_body(ex_root)
               if reader._attrs(b).get("ast_type") == "Return")
    lst = reader._child_by_field(ret, "value")
    extractor_dicts = reader._children_of_field(lst, "elts")
    diag["gap2_extractor_list_node"] = lst
    diag["gap2_extractor_dicts"] = extractor_dicts
    # read extractor[0]'s key SKELETON (the shape every extractor shares).
    keys, _vals = reader.dict_keys_values(extractor_dicts[0])
    diag["gap2_extractor_skeleton_keys"] = [reader.const(k) for k in keys]

    # GAP 3 — the PROSE output: differentiate() builds an impl dict whose `consequence`
    # is a free-text string (out.append({... "consequence": sh["consequence"] ...}) in
    # order_n_postulates). Locate the `consequence` string-key in that append as a node.
    onp_mod = recs["order_n_postulates"]["module"]
    diff_root = recs["order_n_postulates"]["func_roots"]["differentiate"]
    # find the Constant 'consequence' appearing under differentiate (the dict key).
    cons_keys = []
    for n in reader.nodes_of_type("Constant", onp_mod):
        if reader._attrs(n).get("value") == "consequence":
            cons_keys.append(n)
    diag["gap3_prose_consequence_const_nodes"] = cons_keys
    diag["gap3_differentiate_root"] = diff_root
    return diag


