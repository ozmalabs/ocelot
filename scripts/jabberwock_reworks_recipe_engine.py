class GraphReader(att.AstTermEmitter):
    """The agent's graph-walk over its ingested code. Adds only convenience finders on
    top of AstTermEmitter's _attrs / _children / _child_by_field / _children_of_field —
    NO new logic, just locating nodes by ast_type within an ingested module."""

    def __init__(self, substrate):
        super().__init__(substrate, held_leaves={})

    def nodes_of_type(self, ast_type: str, module: str) -> List[int]:
        out = []
        for n in self.s.nodes("AstNode"):
            a = self.s.node(n)["attrs"]
            if a.get("ast_type") == ast_type and a.get("module") == module:
                out.append(n)
        return out

    def func_body(self, func_root: int) -> List[int]:
        return self._children_of_field(func_root, "body")

    def dict_keys_values(self, dict_nid: int):
        keys = self._children_of_field(dict_nid, "keys")
        vals = self._children_of_field(dict_nid, "values")
        return keys, vals

    def const(self, nid: int):
        return self._attrs(nid).get("value")


