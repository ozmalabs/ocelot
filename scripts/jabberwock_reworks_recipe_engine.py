# (3b) REWORK — THE HARVEST-FIX, by TRANSFERRING the working `for name, term_json in
# registry` walk (already in harvest_shape_donors, read off the AST-graph) into the
# empty `for c in substrate.nodes("Concept")` loop body (the `pass`).
#
# The ABSTRACTION: read the working walk's BODY off the graph — its essential step is
# `substrate.shape_of_term(term_json)` over a concept's Term-tree, appended to `out`. The
# TRANSFER: the stubbed loop walks Concept NODES; the only missing wiring is "get each
# concept's Term-tree, then run the SAME shape_of_term step". harvester_shape ALREADY
# ships `lookup_postulate_term(name)` (the Term-tree lookup the stub needs). So the fix
# is: in the concept-walk loop, look up the concept's Term-tree and, when present, run the
# SAME shape_of_term step the working walk runs. We EMIT that as a runnable Python
# closure (the world-adapter that the stub should have been) AND verify it harvests > 0.
# ===========================================================================

def rework_harvest_fix(reader: GraphReader, recs: dict):
    """Read the working `for name, term_json in registry` walk's essential step off the
    AST-graph (its shape_of_term call), and TRANSFER it into a concept-walk closure that
    fills the stub. Returns (provenance, the runnable harvest closure)."""
    hs_mod = recs["harvester_shape"]["module"]
    hsd_root = recs["harvester_shape"]["func_roots"]["harvest_shape_donors"]
    # locate the working walk's `substrate.shape_of_term(...)` step in the graph — the
    # step the stub lacks — as provenance the transfer SOURCE is the agent's own working
    # code. `ingest_ast` does NOT copy an Attribute's `attr` field (only value/id/arg/
    # name/n/s — the NAMED ingest residual), so we locate the call STRUCTURALLY: a Call
    # whose func is an Attribute over the `substrate` Name (the working walk's
    # substrate.shape_of_term / substrate.shapes_compatible calls). This reads the
    # transfer source off the graph by a field the ingest DOES carry (the Name id).
    shape_calls = []
    for call in reader.nodes_of_type("Call", hs_mod):
        func = reader._child_by_field(call, "func")
        if func is None or reader._attrs(func).get("ast_type") != "Attribute":
            continue
        recv = reader._child_by_field(func, "value")
        if recv is not None and reader._attrs(recv).get("id") == "substrate":
            shape_calls.append(call)
    provenance = {
        "transfer_source": "harvest_shape_donors' working `for name, term_json in "
                           "registry` walk (substrate.shape_of_term over the concept's "
                           "Term-tree, appended to out)",
        "shape_of_term_call_nodes": shape_calls,
        "concept_walk_func_root": hsd_root,
        "missing_wiring": "the concept-walk loop body (`pass`) does not fetch each "
                          "concept's Term-tree before the shape step; "
                          "lookup_postulate_term already ships the lookup it needs",
    }

    # the EMITTED harvest-fix: a world-adapter closure that walks Concept NODES, fetches
    # each one's Term-tree via the SHIPPED lookup_postulate_term, and runs the SAME
    # shape_of_term step the working walk runs. This is the loop body the `pass` omitted.
    def harvest_concept_terms(substrate) -> list:
        from domains.harvester_shape import lookup_postulate_term
        out = []
        for c in substrate.nodes("Concept"):
            a = substrate.node(c)["attrs"]
            name = str(a.get("name", "") or "")
            if not name:
                continue
            term_json = lookup_postulate_term(name)   # the SHIPPED Term-tree lookup
            if term_json is None:
                continue
            try:
                shape = substrate.shape_of_term(term_json)   # the SAME working step
            except Exception:
                continue
            out.append({"name": name, "shape": shape, "term_json": term_json,
                        "origin": "concept_walk_harvest_fix"})
        return out

    return provenance, harvest_concept_terms


