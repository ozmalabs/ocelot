# (3a) REWORK — THE NEW EXTRACTOR, by ABSTRACTING extractor[0]'s dict skeleton off the
# AST-graph and TRANSFERRING it (re-filling the holes) to the new shape-class.
#
# The ABSTRACTION: read extractor[0]'s 7-key shape off the graph (gap2_extractor_skeleton
# _keys). The TRANSFER: produce a NEW dict with the SAME keys, holes re-filled for the
# "reduce-over-structured-family" shape-class. The fill is NOT free LLM prose: each field
# is DERIVED from the agent's own material —
#   · id            : the shape-class name (the gap the 12 lack);
#   · evidence/triggers : the structural markers of "an extremum/quantity over a
#                     structured/indexed FAMILY" — read off the agent's OWN euler/f-vector
#                     vocabulary (range / over each dimension / per-level / max over);
#   · consequence   : the structural entailment (a max/extremum over an indexed family is
#                     a REDUCE over the family — count the occupied levels, range, etc.);
#   · match_keys/name_signals/name_keys_for : the capability the consequence names.
# This MIRRORS analogy._skeletonize + instantiate (hollow the holes, re-fill for the new
# domain) — applied to an EXTRACTOR dict read off the agent's code-as-graph.
