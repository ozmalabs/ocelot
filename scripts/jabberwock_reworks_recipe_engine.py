def run_reworked_loop(s, recipe: str) -> dict:
    caps = dict(reason.CAPABILITIES)
    res = cg.ground_computation(s, "dimension", recipe, capabilities=caps)
    out = {"recipe": recipe, "grounded": res["grounded"],
           "installed": res["installed"], "parts": res.get("parts"),
           "term": res.get("term"), "checks": [], "self_verified": False}
    if not (res["grounded"] and res["installed"]):
        out["reason"] = res.get("reason")
        return out
    knowns = load_known_values()
    ok = True
    for arg, expected in knowns:
        try:
            got = reason.solve({"dimension": dict(arg)}, {}, capabilities=caps)
        except Exception as e:                  # noqa: BLE001
            got, ok = f"error:{e}", False
            out["checks"].append({"arg": arg, "expected": expected,
                                  "got": got, "ok": False})
            break
        passed = (int(got) == int(expected))
        ok = ok and passed
        out["checks"].append({"arg": {k: ("<complex>" if k == "complex" else v)
                                      for k, v in arg.items()},
                              "expected": expected, "got": got, "ok": passed})
    out["self_verified"] = ok
    return out


