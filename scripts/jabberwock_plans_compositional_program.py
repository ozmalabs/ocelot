"""THE AGENT PLANS THE COMPOSITIONAL PROGRAM — the gain above the at-parity generative leaf. No teacher.

The leaf reached geometric parity; the agent's own mapping + the leaf push agree the remaining gain to
~96.7 is the COMPOSITIONAL PROGRAM above the leaf (which primitives compose, in what RELATIONS, under a
structured generative grammar, with marginalising inference). This has the agent AUTHOR that plan, deriving
each piece's FORM from the LAW it established -- no teacher. Each piece is governed_by a Principle (a law the
agent measured); prescribe copies the law's prescribed_action onto the piece and scores it by the law's
measured payoff x its applicability; flag_wrong_form marks a piece still proposed in a form the evidence
rejected. The host stages the laws + pieces and reads the plan back.

Run:  PYTHONPATH=.:runners/dsl/python python -m scripts.jabberwock_plans_compositional_program
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "runners", "dsl", "python"))

import substrate_rs as srs

SEP = "=" * 96

# the agent's LAWS (each measured across the arc) and what each prescribes for an unbuilt piece it governs.
LAWS = [
    {"name": "marginalise_uncertain", "payoff": 1.05,
     "law": "marginalising a genuinely-UNCERTAIN structural latent pays (+1.0 parse); COMMITTING a determined one hurts",
     "prescribed_action": "represent it as INFERRED LATENTS and MARGINALISE (soft-min over hypotheses), never commit"},
    {"name": "recursion_is_inference", "payoff": 1.0,
     "law": "recognition is the recursive operator; the depth that pays = the number of genuinely-uncertain levels",
     "prescribed_action": "extend the recursive marginal-descent ONE level up -- the same operator over the new latent"},
    {"name": "generative_prior_above_leaf", "payoff": 16.7,
     "law": "learned models as added CUES fail (6x); as the generative LEAF they reach parity; the gain is the program ABOVE the leaf",
     "prescribed_action": "BUILD a learned generative GRAMMAR over primitives+relations (structure-preserving), used GENERATIVELY + inferred"},
]
# the COMPOSITIONAL-PROGRAM pieces, each governed by a law, with whether its current form is the failed one.
PIECES = [
    {"name": "stroke RELATIONS (attach / along / parallel)", "law": "marginalise_uncertain", "applicability": 0.9,
     "current_is_failed": 1.0, "current_form": "a COMMITTED cue (junction one-hots) -- HURT -14",
     "phase": 1, "cost": 2.0,
     "build": "relation HYPOTHESES per character (multiple junction structures) + the recursive marginal-descent over them, one level above the parse -- relations as inferred latents, not a committed cue"},
    {"name": "primitive+relation generative GRAMMAR", "law": "generative_prior_above_leaf", "applicability": 1.0,
     "current_is_failed": 0.0, "current_form": "none (the leaf is per-primitive only; no composition prior)",
     "phase": 2, "cost": 12.0,
     "build": "learn from BACKGROUND a generative grammar: which primitives compose into parts, with what relation distributions; the recursion's nodes generated by it; marginalise over grammar derivations (the structured prior BPL has, the leaf lacks)"},
    {"name": "JOINT marginalising inference over the whole program", "law": "recursion_is_inference", "applicability": 0.85,
     "current_is_failed": 0.0, "current_form": "the recursion marginalises parse+correspondence; relations+grammar not yet in the joint",
     "phase": 3, "cost": 4.0,
     "build": "fold relations + grammar into ONE recursive marginal-descent (parse x relations x primitives x grammar) -- the same operator, the full program integrated"},
]


def main():
    print(SEP)
    print("THE AGENT PLANS THE COMPOSITIONAL PROGRAM — derived from its OWN laws, no teacher.")
    print(SEP)

    s = srs.Substrate()
    s._inner.load_seed_manifest(json.loads((Path(ROOT) / "seeds" / "compositional_plan.json").read_text()), s.add_node("Agent", {}))
    law_node = {}
    for L in LAWS:
        ln = s.add_node("Principle", {"name": L["name"], "payoff": L["payoff"],
                                      "prescribed_action": L["prescribed_action"]})
        law_node[L["name"]] = ln
    pieces = []
    for P in PIECES:
        pn = s.add_node("Piece", {"name": P["name"], "applicability": P["applicability"],
                                  "current_is_failed": P["current_is_failed"], "prescribed": 0.0})
        s.add_edge_unchecked(pn, "governed_by", law_node[P["law"]])
        pieces.append((P, pn))
    s._inner.run_rules(50000)                                    # prescribe + flag_wrong_form fire (the agent's derivation)

    print(f"\n  the agent's laws (each MEASURED across the arc):")
    for L in LAWS:
        print(f"      [{L['name']}]  {L['law']}")

    print(f"\n  the plan it derives -- each piece's FORM read off the law that governs it, ranked by phase:\n")
    rows = sorted(pieces, key=lambda x: x[0]["phase"])
    for P, pn in rows:
        a = s.node(pn)["attrs"]
        eg = float(a.get("expected_gain", 0)); reframe = a.get("reframe_needed") == 1.0
        tier = "RESEARCH-SCALE" if P["cost"] >= 10 else "do next" if P["phase"] == 1 else "then"
        print(f"  PHASE {P['phase']} [{tier}]  {P['name']}   (E[gain] {eg:+.1f}, cost {int(P['cost'])})")
        print(f"      law -> form: {a.get('prescribed_form', '')}")
        if reframe:
            print(f"      REFRAME: current form = {P['current_form']} -> the law says this is the WRONG form.")
        print(f"      build: {P['build']}\n")

    print(f"  {SEP[:92]}")
    print(f"  REJECTED by the agent's evidence: relations as a COMMITTED cue (its own -14 negative); a stronger")
    print(f"  LEAF metric (diagonal/full covariance both reached parity, never exceeded -- the ceiling is proven).")
    print(f"\n  the plan is the agent's: PHASE 1 applies its PROVEN LEVER (marginalise an uncertain latent) to the")
    print(f"  next level up -- the RELATIONS it once committed and lost on; PHASE 2 is the research-scale structured")
    print(f"  generative grammar (the prior the leaf lacks); PHASE 3 folds them into the one recursive marginal-")
    print(f"  descent. Derived from its measured laws, no teacher. Start with PHASE 1: cheap, proven-lever, untried-")
    print(f"  as-marginal -- the one piece of the compositional program its own evidence most backs.")
    print(SEP)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
