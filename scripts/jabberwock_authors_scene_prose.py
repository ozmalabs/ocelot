"""The jabberwock AUTHORS the GRAMMAR it narrates a scene with — so the prose is
generated by its own Render engine over graph-resident rules, not Python f-strings.
(Creator: "I want the prose to be entirely generated by the jabberwock.")

It already renders a relational meaning (left FORM right) via its relations language.
What it lacks is (1) how to turn a perceived FIGURE node into a noun phrase, and
(2) the wording for the three things it now recognises (a cross landmark, two figures
of the same shape, its own body). It asks its Claude-teacher for that grammar, installs
it, verifies the engine renders real sentences, and persists it. The Python only
supplies the MEANING (its recognition) thereafter; the surface is the engine's.
"""
from __future__ import annotations
import json, os, re, sys
os.environ.setdefault("ARC3_THIN", "1")
sys.path.insert(0, "."); sys.path.insert(0, "scripts")
from substrate.world_adapter import WorldAdapter
from substrate.boot_all import load_all_seeds
from scripts.claude_teacher import make_ask

SEED = "seeds/scene_prose.json"

Q = """A graph-native agent narrates what it sees by RENDERING a meaning tree with its own engine.
It renders a relation as: render(left) + " " + FORM + " " + render(right). A leaf renders its
`form` string. I need you to author the missing GRAMMAR as JSON.

(1) A render-rule TEMPLATE that turns a perceived FIGURE node into a noun phrase. A figure node
has string/int attrs: "colour" (e.g. "blue","white-and-grey"), "row", "col". Template spec grammar
(nested JSON lists):
  ["Cat", <item>, <item>, ...]            sequence
  ["Surface","text","some literal words"] literal text
  ["Slot","colour"]                       the value of the node's "colour" attr (also "row","col")
Example for a different shape: ["Cat",["Surface","text","the "],["Slot","colour"],["Surface","text"," shape"]]

(2) The WORDING (plain strings) for three statements the agent makes, where <L>/<R> are figures it
renders with the template above:
  - a CROSS landmark:        "<L> FORM_cross LEAF_cross"   (e.g. FORM_cross="is", LEAF_cross="a cross landmark on the floor")
  - SAME SHAPE (one rotated): "<L> FORM_same <R>"
  - its own BODY:            "<L> FORM_body LEAF_body"     (the figure it found is itself by MOVING — it responded to a control)

Output ONLY this JSON between the markers (fill every field; keep it natural, first-person for the body):
@@@grammar
{{"figure_template": <template spec>,
  "figure_binding": ["colour","row","col"],
  "form_cross": "...", "leaf_cross": "...",
  "form_same": "...",
  "form_body": "...", "leaf_body": "..."}}
@@@end{err}"""


def _check(agent, gram):
    """Install the authored grammar and VERIFY the engine renders real sentences."""
    from substrate import Cat, Surface, Slot, Render
    agent.install_relations_renderer()
    tmpl = agent._spec_to_renderer_term(gram["figure_template"])
    agent.install_render_rule("relations", "FigNode", template=tmpl,
                              binding_pattern=gram["figure_binding"])

    def fig(colour, r, c):
        return agent.s.add_node("FigNode", {"colour": colour, "row": int(r), "col": int(c)})

    def rel(form, left, right):
        n = agent.s.add_node("Term.Relation", {"form": form})
        agent.inner.add_edge_unchecked(n, "child.left", left)
        agent.inner.add_edge_unchecked(n, "child.right", right)
        return agent._render_node(n)

    def leaf(t):
        return agent.s.add_node("Term.Leaf", {"form": t})

    out = {
        "cross": rel(gram["form_cross"], fig("white-and-grey", 32, 21), leaf(gram["leaf_cross"])),
        "same": rel(gram["form_same"], fig("blue", 11, 36), fig("blue", 56, 4)),
        "body": rel(gram["form_body"], fig("blue", 47, 36), leaf(gram["leaf_body"])),
    }
    ok = all(isinstance(v, str) and len(v.split()) >= 5 for v in out.values())
    return ok, out


def run(max_repair=3):
    agent = WorldAdapter(seeds=()); load_all_seeds(agent)
    ask = make_ask(timeout=300.0, preamble="")
    prior = ""
    for attempt in range(1, max_repair + 2):
        print(f"--- consult attempt {attempt} ---", flush=True)
        m = re.search(r"@@@grammar\s*(.+?)\s*@@@end", ask(Q.format(err=prior)) or "", re.DOTALL)
        if not m:
            prior = "\n\nReturn ONLY the JSON between @@@grammar and @@@end."; continue
        try:
            gram = json.loads(m.group(1).strip())
        except Exception as e:
            prior = f"\n\nJSON parse error: {e}."; print("  bad json:", e, flush=True); continue
        try:
            ok, out = _check(agent, gram)
        except Exception as e:
            prior = f"\n\nInstalling/rendering your grammar raised {type(e).__name__}: {e}. Fix the template spec."
            print("  render raised:", e, flush=True); continue
        for k, v in out.items():
            print(f"  {k}: \"{v}\"", flush=True)
        if ok:
            json.dump(gram, open(SEED, "w"), indent=2)
            print(f"\n✓ the jabberwock authored its scene grammar; persisted to {SEED}.\n"
                  "  every narration sentence is now rendered by ITS engine over these rules.", flush=True)
            return True
        prior = "\n\nSome sentences were empty/too short. Fill every field with natural wording."
        print("  too short; feeding back.", flush=True)
    print("\n✗ scene grammar not authored.", flush=True)
    return False


if __name__ == "__main__":
    sys.exit(0 if run() else 1)
