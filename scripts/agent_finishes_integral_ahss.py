def step_run_differentials(s, caps, asm) -> dict:
    banner("3. RUN the differentials — d_2 : E^2_{p,q} -> E^2_{p-2,q+1} (dual Sq^2, "
           "paired with Omega^Spin_1 = Z/2), higher d_r; track the degree-12 torsion")
