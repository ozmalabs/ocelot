def _fmt_group(free, torsion):
    parts = []
    if free == 1:
        parts.append("Z")
    elif free > 1:
        parts.append(f"Z^{free}")
    parts += [f"Z/{d}" for d in torsion]
    return " (+) ".join(parts) if parts else "0"


