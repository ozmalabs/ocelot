    print("  bidegree (p+2,q-1)) or maps IT to a nonzero target (bidegree (p-2,q+1)).")
    print("  The agent traces each degree-12 torsion class through the d_2 pattern,")
    print("  reading the source/target cells off the assembled integral E_2 page.\n")

    def e2(p, q):
        if p < 1 or q < 0:
            return {"free": 0, "torsion_2rank": 0}
        return reason.solve({"bg2_integral_e2": {"p": p, "q": q}}, {}, capabilities=caps)

    resolved = []          # torsion classes the differentials KILL (rigorously)
    unresolved = []        # torsion classes the d_2/d_r machinery CANNOT close
    for (p, q), r in asm["tors_cells"]:
        src = (p + 2, q - 1)     # d_2 INTO (p,q)
        tgt = (p - 2, q + 1)     # d_2 OUT of (p,q)
        gs = e2(*src)
        gt = e2(*tgt)
        src_live = (gs["free"] or gs["torsion_2rank"])
        tgt_live = (gt["free"] or gt["torsion_2rank"])
        print(f"  E^2_{{{p},{q}}} = (Z/2)^{r}:")
        print(f"    d_2 source (p+2,q-1)=({src[0]},{src[1]}): "
              f"{_fmt_group(gs['free'], [2] * gs['torsion_2rank'])} "
              f"{'(a class CAN map onto it)' if src_live else '(empty — no source)'}")
        print(f"    d_2 target (p-2,q+1)=({tgt[0]},{tgt[1]}): "
              f"{_fmt_group(gt['free'], [2] * gt['torsion_2rank'])} "
              f"{'(it CAN map out nonzero)' if tgt_live else '(empty — no target)'}")
