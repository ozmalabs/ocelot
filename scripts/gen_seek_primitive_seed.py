"""Generator for seeds/seek_primitive.json — the held SEEK faculty (an AFFORDANCE the agent composes with).

The jabberwock's compose-from-faculties design treats SEEK as a held part: move the self toward a target cell
(tgt_r, tgt_c) it reads off its own node, death-gated. A new faculty (LEAD/DODGE/...) is then just a small
minted PRODUCER that writes (tgt_r,tgt_c) — composition is via the shared attr, no change to SEEK. This is the
host-provided primitive; the agent authors the producers.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ACTS = ["Up", "Down", "Left", "Right"]
def V(n): return {"type":"Var","name":n}
def L(v): return {"type":"Lit","value":v}
def A(node,k): return {"type":"Attr","node":node,"key":k}
def P(var,k): return {"type":"Plus","items":[A(V(var),k),L(0.0)]}
def And(i): return {"type":"And","items":i}
def Or(i): return {"type":"Or","items":i}
def Eq(a,b): return {"type":"Eq","a":a,"b":b}
def Lt(a,b): return {"type":"Lt","a":a,"b":b}
def Gt(a,b): return {"type":"Gt","a":a,"b":b}
def Gte(a,b): return {"type":"Gte","a":a,"b":b}
def Plus(i): return {"type":"Plus","items":i}
def Minus(a,b): return {"type":"Minus","a":a,"b":b}
def Neg(a): return {"type":"Neg","arg":a}
def Mx(i): return {"type":"Max","items":i}
def Ab(x): return Mx([x,Neg(x)])
def Ite(c,t,o): return {"type":"IfThenElse","cond":c,"then":t,"other":o}
R,G=V("r"),V("game")
def score(a):
    nr=Plus([P("r","cy"),P("r",f"resp_{a}_dr")]); nc=Plus([P("r","cx"),P("r",f"resp_{a}_dc")])
    dist=Plus([Ab(Minus(nr,P("r","tgt_r"))),Ab(Minus(nc,P("r","tgt_c")))])
    die=Or([Lt(nr,L(0.0)),Gt(nr,Minus(A(G,"h"),L(1.0))),Lt(nc,L(0.0)),Gt(nc,Minus(A(G,"w"),L(1.0)))])
    return Ite(die,L(-1.0e9),Neg(dist))   # maximize -dist = approach (tgt) ; death-gated
def choose():
    sU,sD,sL,sR=(score(a) for a in ACTS)
    return Ite(And([Gte(sU,sD),Gte(sU,sL),Gte(sU,sR)]),L("Up"),
           Ite(And([Gte(sD,sL),Gte(sD,sR)]),L("Down"),
           Ite(Gte(sL,sR),L("Left"),L("Right"))))
seed={"id":"seek_primitive","version":"1.0.0","depends_on":["nd_action_correlation"],
 "description":"Held SEEK faculty (affordance): the self (controllable region) moves death-gated toward the "
   "target cell (tgt_r,tgt_c) on its own node, via argmax over the learned control basis resp_<A>. A new "
   "faculty is a small minted PRODUCER that writes (tgt_r,tgt_c); SEEK is reused unchanged (compose via the "
   "shared attr). Host-provided primitive. Generated by scripts/gen_seek_primitive_seed.py.",
 "microtheory":{"name":"seek_primitive","description":"move toward self.tgt; producers feed the target"},
 "nodes":[],"edges":[],"productions":[],
 "rules":[{"name":"seek_to_target","comment":"death-gated argmax over resp_<A> toward (self.tgt_r,self.tgt_c); "
   "fires only when a producer has set tgt_set>0.5, so SEEK is inert until a faculty feeds it a target.",
   "match":[["game","has_region","r"]],
   "where":And([Eq(A(R,"axis_kind"),L("controllable")),Lt(P("r","count"),L(1.5)),Gt(P("r","tgt_set"),L(0.5))]),
   "effects":[["set_attr","game","chosen_action",{"__term__":choose()}]]}]}
out=os.path.join(ROOT,"seeds","seek_primitive.json"); tmp=out+".tmp"
json.dump(seed,open(tmp,"w"),indent=1); json.load(open(tmp)); os.replace(tmp,out)
print(f"wrote + validated seeds/seek_primitive.json (1 rule)")
