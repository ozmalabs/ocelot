# KNOWN values below are only the independent ground-truth CHECK.
# ---------------------------------------------------------------------------
S1 = [[0], [1], [2], [0, 1], [1, 2], [0, 2]]                    # circle  b=(1,1)
DISK = S1 + [[0, 1, 2]]                                         # disk    b=(1,0,0)
S2 = [[0], [1], [2], [3],
      [0, 1], [0, 2], [0, 3], [1, 2], [1, 3], [2, 3],
      [0, 1, 2], [0, 1, 3], [0, 2, 3], [1, 2, 3]]               # 2-sphere b=(1,0,1)


def _top_dim(complex_):
    return max(len(s) - 1 for s in complex_)


# ===========================================================================
# THE OPERATOR DEFINITIONS the agent READS. These are the operator's GROUNDED
# DEFINITION (the textbook equation in the index variable), the SAME register
# compute_homology.py feeds (BETTI_DEF). They are NOT a Python implementation —
# they are the prose-equation the agent comprehends + COMPOSES into a Term-tree.
# ===========================================================================
DEFS = {
    "betti": (
        "betti(complex, k) = "
        "cardinality(simplices_of_dim(complex, k)) "
        "- matrix_rank(boundary_matrix(complex, k)) "
        "- matrix_rank(boundary_matrix(complex, k + 1))"),
    "euler": (
        "euler(complex, d) = "
        "sum{i in 0..d : neg_one_pow(i) * "
        "cardinality(simplices_of_dim(complex, i))}"),
}


# ===========================================================================
# (1) THE SELF-GENERATED COMPUTE — ground_computation READS the def + COMPOSES the
# Term-tree over HELD primitives. The faculty is the AGENT'S COMPOSITION (the
# returned `term`), installed as a runnable dispatcher in `caps`. NOT hand-authored.
# ===========================================================================
def self_generate_compute(s, op_name, definition, caps):
    res = cg.ground_computation(s, op_name, definition, capabilities=caps)
    return res


# ===========================================================================
# (2) THE SELF-GENERATED GENERATOR QUERIES — derived from the definition's PARTS.
# Each HELD primitive the compute COMPOSES OVER is a PRESUPPOSITION the operator's
# value DEPENDS ON; the agent emits one query per presupposed primitive. This is
# the order-1 lift (order_n_communication) driven by the DEFINITION's structure
# (the `parts` ground_computation read off the typed tree), NOT a hand-authored
# per-family _presupposed_needs branch — a paraphrase grounding to the same parts
# generates the same queries; a different operator generates a different set.
# ===========================================================================
# the structural meaning each held primitive carries — the agent's grounded
# primitive vocabulary (read off reason.CAPABILITIES' own doc tier), so the query
# text is the QUESTION the operator's USE of that primitive raises. NOT a per-family
# table: it is keyed by the PRIMITIVE, shared across every operator that uses it.
_PRIMITIVE_PRESUPPOSITION = {
    "boundary_matrix": "the BOUNDARY OPERATOR matrix in coordinates (the held ∂)",
    "matrix_rank": "the RANK over a field (Gaussian elimination, GF(2))",
    "simplices_of_dim": "the k-DIMENSIONAL FACES (the f-vector entry)",
    "cardinality": "the CARDINALITY of a face set (a count)",
    "neg_one_pow": "the ALTERNATING SIGN (-1)^i (the inclusion-exclusion parity)",
    "smith_normal_form": "the INVARIANT FACTORS over Z (torsion)",
    "integer_boundary_matrix": "the SIGNED boundary over Z",
}


def self_generate_queries(op_name, parts):
    """SELF-GENERATE the order-1 queries from the compute's PARTS. Each held
    primitive the operator's definition composes over RAISES the query 'what is
    <that primitive> of the object?' — the fact the operator's value PRESUPPOSES.
    Uniform over operators (keyed by the primitive), not a hand-authored branch."""
    queries = []
    for p in sorted(parts):
        meaning = _PRIMITIVE_PRESUPPOSITION.get(p)
        if meaning is None:
            continue  # an arithmetic glue primitive (minus/plus/times) raises no fact
        queries.append({
            "needs": f"what is {meaning} that {op_name} composes over?",
            "presupposed_primitive": p,
            "provenance": (f"order-1: {op_name}'s self-generated compute composes "
                           f"over the held primitive {p!r} -> its value is a "
                           f"presupposition"),
        })
    return queries


# ===========================================================================
# (3) ROUTE — the typed op(object, index) routes to the installed dispatcher.
# comprehend_asked_invariant TYPES the asked phrase into op(object, index); the
# routing binds the concrete complex to `complex` and the read index to `k`/`d`,
# then evaluates the SELF-GENERATED Term-tree via reason.solve over `caps`.
# ===========================================================================
def route_and_compute(op_name, complex_, index, caps):
    """ROUTE the typed query to the self-generated dispatcher + COMPUTE the number.
    The bound query mirrors the typed tree's slots (object -> complex, index ->
    k/d). reason.solve dispatches to caps[op_name] (the installed composition)."""
    if op_name == "betti":
        return reason.solve({"betti": {"complex": complex_, "k": index}}, {},
                            capabilities=caps)
    if op_name == "euler":
        return reason.solve({"euler": {"complex": complex_, "d": index}}, {},
                            capabilities=caps)
    raise ValueError(op_name)


# ===========================================================================
# (4) INDEPENDENT VALIDATION — a SECOND method, never reverse-engineered.
# ===========================================================================
def betti_reference(complex_, k):
    """The reference Betti via the textbook formula over the SNF/GF(2) rank
    (reason internals) — an INDEPENDENT path (not the installed dispatcher's
    composition). b_k = #k-simplices - rank ∂_k - rank ∂_{k+1}."""
    nk = len(reason._simplices_of_dim(complex_, k))
    rk = reason._matrix_rank_gf2(reason._boundary_matrix(complex_, k))
    rk1 = reason._matrix_rank_gf2(reason._boundary_matrix(complex_, k + 1))
    return nk - rk - rk1


def euler_reference_brute(complex_):
    """The reference Euler characteristic via a DIRECT brute face-count (a plain
    Counter over simplex sizes) — shares NO code with the held sum_where path.
    chi = sum_i (-1)^i f_i."""
    sizes = Counter(len(s) - 1 for s in complex_)
    top = max(sizes)
    return sum((-1) ** i * sizes.get(i, 0) for i in range(top + 1))


# the KNOWN textbook values (the agent never sees these in the compute path).
KNOWN_BETTI = {
    "S^1 (circle)": (S1, [1, 1]),
    "disk": (DISK, [1, 0, 0]),
    "S^2 (2-sphere)": (S2, [1, 0, 1]),
}
KNOWN_EULER = {"S^1 (circle)": (S1, 0), "disk": (DISK, 1), "S^2 (2-sphere)": (S2, 2)}


# ===========================================================================
def demonstrate_family(s, op_name, caps):
    banner(f"FAMILY: {op_name}  — self-generate COMPUTE + GENERATE, end-to-end")
    definition = DEFS[op_name]
    print(f"  (0) the operator's GROUNDED DEFINITION (read, the textbook equation):")
    print(f"      {definition}")

    # (1) SELF-GENERATE the COMPUTE by COMPOSITION ---------------------------
    print(f"\n  (1) SELF-GENERATE the COMPUTE — ground_computation READS the def +")
    print(f"      COMPOSES a runnable Term-tree over HELD primitives (NOT hand-authored):")
    held_before = op_name in caps
    res = self_generate_compute(s, op_name, definition, caps)
    print(f"      held before? {held_before}   grounded now? {res['grounded']}")
    print(f"      PROVENANCE — held primitives the compute composes over (parts):")
    print(f"        {res['parts']}")
    all_held = all(cg._is_held_primitive(p, caps) or p == op_name
                   for p in res['parts'])
    print(f"      every part a HELD primitive (composable-now)? {all_held}")
    print(f"      THE COMPOSITION TREE (the faculty = this tree, the agent's):")
    print(f"        {json.dumps(res['term'])}")
    print(f"      combination stored as a RUNNABLE tree? "
          f"{res.get('ground', {}).get('combination_is_tree')}   installed? "
          f"{res['installed']}")

    # (2) SELF-GENERATE the GENERATOR queries from the def's PARTS -----------
    print(f"\n  (2) SELF-GENERATE the GENERATE queries — from the definition's PARTS")
    print(f"      (each held primitive the compute presupposes = a query), the order-1")
    print(f"      lift driven by the DEFINITION, NOT a hand-authored per-family branch:")
    queries = self_generate_queries(op_name, res['parts'])
    for q in queries:
        print(f"        · [{q['presupposed_primitive']:18s}] {q['needs']}")
    print(f"      -> {len(queries)} self-generated queries (was 0 at the stall)")

    # (3) END-TO-END: TYPE -> GENERATE -> ROUTE -> COMPUTE -> NUMBER ----------
    print(f"\n  (3) END-TO-END — TYPE -> GENERATE -> ROUTE -> self-gen COMPUTE -> NUMBER")
    known = KNOWN_BETTI if op_name == "betti" else KNOWN_EULER
    all_ok = True
    for inst_name, payload in known.items():
        complex_ = payload[0]
        # TYPE: comprehend the asked phrase into op(object, index) on the real reader.
        if op_name == "betti":
            asked = _pd.comprehend_asked_invariant(
                "Let D denote the abstract simplicial complex on six vertices. "
                "We study its homology. What is the first betti number of D?")
            typed_repr = asked.repr
            # COMPUTE the full Betti VECTOR (each k), ROUTE+COMPUTE per dimension.
            top = _top_dim(complex_)
            got = [route_and_compute("betti", complex_, k, caps)
                   for k in range(top + 1)]
            want = payload[1]
            ref = [betti_reference(complex_, k) for k in range(top + 1)]
            ok = (got == want == ref)
            all_ok = all_ok and ok
            print(f"      · {inst_name:16s} TYPE={typed_repr!r}")
            print(f"          self-gen COMPUTE b = {got}   reference(SNF/GF2) = {ref}"
                  f"   known = {want}   {'OK' if ok else 'X'}")
        else:
            asked = _pd.comprehend_asked_invariant(
                "Let X denote the space under study. We study its topological "
                "invariants. What is the euler characteristic of X?")
            typed_repr = asked.repr
            d = _top_dim(complex_)
            got = route_and_compute("euler", complex_, d, caps)
            want = payload[1]
            ref = euler_reference_brute(complex_)
            ok = (got == want == ref)
            all_ok = all_ok and ok
            print(f"      · {inst_name:16s} TYPE={typed_repr!r}")
            print(f"          self-gen COMPUTE χ = {got}   reference(brute f-vector)"
                  f" = {ref}   known = {want}   {'OK' if ok else 'X'}")

    print(f"\n  (4) VALIDATION — every self-gen number matches the SECOND independent")
    print(f"      method AND the known textbook value (not reverse-engineered): "
          f"{'PASS' if all_ok else 'FAIL'}")
    return all_ok, res['parts']


