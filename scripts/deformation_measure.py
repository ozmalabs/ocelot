# ------------------------- world I/O: stimuli (mechanical) -------------------------
def dense_cells(cells, s=SCALE):
    """Integer dense cell set — each unit cell becomes an s x s lattice block."""
    out = set()
    for (r, c) in cells:
        for i in range(s):
            for j in range(s):
                out.add((r * s + i, c * s + j))
    return sorted(out)


def rms_radius(intcells):
    mx = sum(p[0] for p in intcells) / len(intcells)
    my = sum(p[1] for p in intcells) / len(intcells)
    return math.sqrt(sum((x - mx) ** 2 + (y - my) ** 2 for x, y in intcells) / len(intcells))


def norm(intcells):
    """Integer lattice cells -> unit-RMS-radius float point set.

    The rounding to the lattice already happened (in-frame INTEGER); this normalization
    is a CROSS-FRAME map, so its floats are legitimate (CLAUDE.md's frame/continuum
    invariant). Unit-RMS is the canonical scale AND is required because uniform scale is
    identity-preserving per the similarity rung.
    """
    mx = sum(p[0] for p in intcells) / len(intcells)
    my = sum(p[1] for p in intcells) / len(intcells)
    cen = [(x - mx, y - my) for x, y in intcells]
    r = math.sqrt(sum(x * x + y * y for x, y in cen) / len(cen)) or 1.0
    return [[x / r, y / r] for x, y in cen]


def smooth_warp(cells, amp):
    """Low-frequency sinusoidal displacement field, ROUNDED back to the integer lattice.
    The warp is a cross-frame map (real amplitude); the observation stays stepped."""
    rs = [r for r, _ in cells]
    cs = [c for _, c in cells]
    h = max(1, max(rs) - min(rs))
    w = max(1, max(cs) - min(cs))
    r0, c0 = min(rs), min(cs)
    return sorted({(round(r + amp * math.sin(math.pi * (c - c0) / w)),
                    round(c + amp * math.sin(math.pi * (r - r0) / h))) for r, c in cells})


def shear_y(cells, k):
    return sorted({(r, round(c + k * r)) for r, c in cells})


def rand_polyomino(seed, n=5):
    """Random CONNECTED n-cell polyomino — the sibling rungs' own floor stimulus."""
    rng = random.Random(seed)
    cells = {(0, 0)}
    while len(cells) < n:
        r, c = rng.choice(sorted(cells))
        dr, dc = rng.choice([(0, 1), (0, -1), (1, 0), (-1, 0)])
        cells.add((r + dr, c + dc))
    mr = min(r for r, _ in cells)
    mc = min(c for _, c in cells)
    return sorted((r - mr, c - mc) for r, c in cells)


def _canon_forms(cells):
    """All 8 D4 images, each normalized to the origin — for the held-shape exclusion."""
    forms = set()
    cur = sorted(cells)
    for _ in range(4):
        cur = sorted((c, -r) for r, c in cur)
        mr = min(r for r, _ in cur); mc = min(c for _, c in cur)
        cur = sorted((r - mr, c - mc) for r, c in cur)
        forms.add(tuple(cur))
        ref = sorted((r, -c) for r, c in cur)
        mr = min(r for r, _ in ref); mc = min(c for _, c in ref)
        forms.add(tuple(sorted((r - mr, c - mc) for r, c in ref)))
    return forms


HELD_FORMS = set()
for _v in OBJ.values():
    HELD_FORMS |= _canon_forms(_v)


def is_held(cells):
    return tuple(sorted(cells)) in HELD_FORMS


# ------------------------------- the graph -------------------------------
CODEBOOK = {k: norm(dense_cells(v)) for k, v in OBJ.items()}
R_BAR = sum(rms_radius(dense_cells(v)) for v in OBJ.values()) / len(OBJ)
EPS = (math.sqrt(2) / 2) / R_BAR            # THE falls-out bound (§13)


def boot(deform=1):
    """Boot the sd loop + the vision_deformation seed; install the codebook + graph data."""
    s, ag = boot_core()
    native = rf._native_eval2(s)
    rf._ensure_shape_decode_loop(s, native, ag)
    native.load_seed_manifest(manifest_for("vision_deformation"), ag)
    s.add_node("Seed", {"id": "vision_deformation", "version": "1.0.0"})
    if deform:
        s.set_attr(ag, "deform", 1.0)
        s.set_attr(ag, "df_eps", EPS)
    for nm in NAMES:
        s.add_node("ShapeSignature", {"name": nm, "points": CODEBOOK[nm],
                                      "kind": "faculty", "faculty": nm, "dim_types": DT})
    return s, ag, native


def identify(s, ag, native, obs_cells):
    """Present one observation; return (status, covered_by) — the GRAPH's verdict."""
    o = s.add_node("Observation", {"points": norm(obs_cells), "status": "df_decoded"})
    s.add_edge(ag, "observed", o)
    native.run_rules()
    at = s.node(o)["attrs"]
    return at.get("status"), at.get("covered_by")


class _T:
    __slots__ = ("_json",)

    def __init__(self, d):
        self._json = d


def components(s, cand_pts, obs_pts):
    """Read the raw SmoothDeformComponents dict — REPORTING only, not a decision."""
    return s.evaluate(_T({"type": "SmoothDeformComponents",
                          "a": {"type": "Lit", "value": cand_pts},
                          "b": {"type": "Lit", "value": obs_pts}}), {})


# --------------------------------- arms ---------------------------------
def arm_invariance(s, ag, native):
    """A1 — 7 objects x 5 smooth-warp amplitudes -> recognized as own identity."""
    ok = wrong = refused = 0
    detail = []
    for nm in NAMES:
        for amp in AMPS:
            st, cov = identify(s, ag, native, smooth_warp(dense_cells(OBJ[nm]), amp))
            if st == "recognized_deformed" and cov == nm:
                ok += 1
            elif st == "df_refused" or cov is None:
                refused += 1
                detail.append([nm, amp, "REFUSED"])
            else:
                wrong += 1
                detail.append([nm, amp, cov])
    return {"correct": ok, "wrong_id": wrong, "refused": refused,
            "total": len(NAMES) * len(AMPS), "detail": detail}


def arm_discrimination(s, ag, native):
    """A2 — untransformed objects must be recognized as themselves, wrong_id 0."""
    ok = wrong = 0
    for nm in NAMES:
        st, cov = identify(s, ag, native, dense_cells(OBJ[nm]))
        if st == "recognized_deformed" and cov == nm:
            ok += 1
        elif cov is not None and cov != nm:
            wrong += 1
    return {"own_identity": ok, "wrong_id": wrong, "total": len(NAMES),
            "exact0": bool(ok == len(NAMES) and wrong == 0)}


def arm_crux(s, ag, native):
    """A3 — the BOUND crux, three conjuncts (§1.1, load-bearing)."""
    # conjunct 1: small smooth warps recognized (read off A1 at the smallest amplitudes)
    small_ok = 0
    for nm in NAMES:
        st, cov = identify(s, ag, native, smooth_warp(dense_cells(OBJ[nm]), 1.0))
        if st == "recognized_deformed" and cov == nm:
            small_ok += 1

    # conjunct 2: the strong shear must be REFUSED
    sh_ref = 0
    sh_detail = []
    for nm in NAMES:
        st, cov = identify(s, ag, native, shear_y(dense_cells(OBJ[nm]), SHEAR_K))
        if st == "df_refused":
            sh_ref += 1
        sh_detail.append([nm, st, cov])

    # conjunct 3: SEPARABILITY — do the two bands overlap?
    # identity-PRESERVING band: winner `total` for each object under each smooth warp.
    preserving = []
    for nm in NAMES:
        for amp in AMPS:
            obs = norm(smooth_warp(dense_cells(OBJ[nm]), amp))
            best = min(components(s, CODEBOOK[k], obs)["total"] for k in NAMES)
            preserving.append([nm, amp, best])
    # identity-CHANGING band: different-object pairs, and the shears.
    changing = []
    for i in NAMES:
        for j in NAMES:
            if i == j:
                continue
            changing.append(["pair", i, j, components(s, CODEBOOK[i], CODEBOOK[j])["total"]])
    for nm in NAMES:
        obs = norm(shear_y(dense_cells(OBJ[nm]), SHEAR_K))
        best = min(components(s, CODEBOOK[k], obs)["total"] for k in NAMES)
        changing.append(["shear", nm, None, best])

    max_pres = max(x[2] for x in preserving)
    min_chg = min(x[3] for x in changing)
    separable = bool(max_pres < min_chg)

    return {
        "c1_small_smooth_recognized": small_ok, "c1_total": len(NAMES),
        "c1_pass": bool(small_ok == len(NAMES)),
        "c2_shear_refused": sh_ref, "c2_total": len(NAMES),
        "c2_pass": bool(sh_ref == len(NAMES)), "c2_detail": sh_detail,
        "c3_max_preserving_total": max_pres, "c3_min_changing_total": min_chg,
        "c3_separable": separable,
        "c3_argmax_preserving": max(preserving, key=lambda x: x[2]),
        "c3_argmin_changing": min(changing, key=lambda x: x[3]),
        "crux_pass": bool(small_ok == len(NAMES) and sh_ref == len(NAMES) and separable),
    }


def arm_floor(s, ag, native):
    """A4 — random non-held connected polyominoes must NOT force-map (seeds 46000-46099)."""
    forced = 0
    tested = 0
    skipped = 0
    detail = []
    for sd in FLOOR_SEEDS:
        cells = rand_polyomino(sd)
        if is_held(cells):
            skipped += 1
            continue
        tested += 1
        st, cov = identify(s, ag, native, dense_cells(cells))
        if st == "recognized_deformed" and cov is not None:
            forced += 1
            detail.append([sd, cov])
    return {"force_maps": forced, "tested": tested, "skipped_held": skipped,
            "detail": detail[:20], "floor_clean": bool(forced == 0)}


def arm_bending_load_bearing(s, ag, native):
    """A5 (§13.2) — toggle the bending clause; measure max|on - off|.

    The bending clause is `bending <= eps^2`. It is LOAD-BEARING iff there exists a
    stimulus whose verdict it changes, i.e. some stimulus with bending > eps^2. We
    measure the max bending actually reached across EVERY stimulus class and compare.
    D == 0 exactly ⇒ decorative ⇒ report as INERT, do not quietly retain.
    """
    mx = 0.0
    where = None
    flips = 0
    for nm in NAMES:
        stimuli = [("smooth", a, smooth_warp(dense_cells(OBJ[nm]), a)) for a in AMPS]
        stimuli.append(("shear", SHEAR_K, shear_y(dense_cells(OBJ[nm]), SHEAR_K)))
        stimuli.append(("plain", 0, dense_cells(OBJ[nm])))
        for kind, p, cells in stimuli:
            obs = norm(cells)
            win = min((components(s, CODEBOOK[k], obs) for k in NAMES),
                      key=lambda d: d["total"])
            if win["bending"] > mx:
                mx = win["bending"]; where = [nm, kind, p]
            # ON  = full bound; OFF = bound without the bending clause
            on = (win["total"] <= EPS and abs(win["shear"]) <= EPS
                  and win["bending"] <= EPS * EPS)
            off = (win["total"] <= EPS and abs(win["shear"]) <= EPS)
            if on != off:
                flips += 1
    for sd in FLOOR_SEEDS:
        cells = rand_polyomino(sd)
        if is_held(cells):
            continue
        obs = norm(dense_cells(cells))
        win = min((components(s, CODEBOOK[k], obs) for k in NAMES), key=lambda d: d["total"])
        if win["bending"] > mx:
            mx = win["bending"]; where = ["floor", "seed", sd]
        on = (win["total"] <= EPS and abs(win["shear"]) <= EPS
              and win["bending"] <= EPS * EPS)
        off = (win["total"] <= EPS and abs(win["shear"]) <= EPS)
        if on != off:
            flips += 1
    return {"max_bending_observed": mx, "bound_eps_squared": EPS * EPS,
            "argmax": where, "verdict_flips_caused_by_bending_clause": flips,
            "D": float(flips), "load_bearing": bool(flips > 0)}


def arm_shear_load_bearing(s, ag, native):
    """A5b (§13.2) — the same toggle for the AFFINE SHEAR clause (the inherited one)."""
    flips = 0
    for nm in NAMES:
        stimuli = [("smooth", a, smooth_warp(dense_cells(OBJ[nm]), a)) for a in AMPS]
        stimuli.append(("shear", SHEAR_K, shear_y(dense_cells(OBJ[nm]), SHEAR_K)))
        for kind, p, cells in stimuli:
            obs = norm(cells)
            win = min((components(s, CODEBOOK[k], obs) for k in NAMES),
                      key=lambda d: d["total"])
            on = (win["total"] <= EPS and abs(win["shear"]) <= EPS
                  and win["bending"] <= EPS * EPS)
            off = (win["total"] <= EPS and win["bending"] <= EPS * EPS)
            if on != off:
                flips += 1
    return {"verdict_flips_caused_by_shear_clause": flips, "D": float(flips),
            "load_bearing": bool(flips > 0)}


def arm_no_bound_control():
    """POSITIVE CONTROL (§13.1) — the SAME graph with the bound effectively removed
    (`df_eps` huge). A mechanism with NO bound must ADMIT the identity-changing shears
    and WRONG-MERGE them onto other identities. This is what makes the crux RISKED:
    the bound is doing real work, and its loss is visible."""
    s, ag, native = boot(deform=1)
    s.set_attr(ag, "df_eps", 1e6)
    admitted = 0
    merges = []
    for nm in NAMES:
        st, cov = identify(s, ag, native, shear_y(dense_cells(OBJ[nm]), SHEAR_K))
        if st == "recognized_deformed":
            admitted += 1
        if cov is not None and cov != nm:
            merges.append([nm, cov])
    return {"admitted": admitted, "total": len(NAMES), "wrong_id_merges": merges,
            "n_merges": len(merges)}


def arm_off_day():
    """A6 (§9) — with the flag ABSENT neither df rule fires; the marker survives."""
    s, ag, native = boot(deform=0)
    o = s.add_node("Observation", {"points": norm(smooth_warp(dense_cells(OBJ["F"]), 1.0)),
                                   "status": "df_decoded"})
    s.add_edge(ag, "observed", o)
    native.run_rules()
    at = s.node(o)["attrs"]
    return {"status": at.get("status"), "covered_by": at.get("covered_by"),
            "inert": bool(at.get("status") == "df_decoded" and at.get("covered_by") is None)}


def run():
    out = {"provenance": _PROV, "objects": NAMES, "scale": SCALE, "amps": AMPS,
           "shear_k": SHEAR_K, "R_bar": R_BAR, "eps": EPS, "eps_squared": EPS * EPS,
           "eps_derivation": "(sqrt(2)/2)/R — integer-lattice half-diagonal in "
                             "unit-RMS-normalized units; R = codebook mean RMS radius "
                             "(falls out, VISION_PROTOCOL §13)",
           "floor_seeds": [FLOOR_SEEDS[0], FLOOR_SEEDS[-1]]}

    s, ag, native = boot(deform=1)
    out["A1_invariance"] = arm_invariance(s, ag, native)
    out["A2_discrimination"] = arm_discrimination(s, ag, native)
    out["A3_crux"] = arm_crux(s, ag, native)
    out["A4_floor"] = arm_floor(s, ag, native)
    out["A5_bending_load_bearing"] = arm_bending_load_bearing(s, ag, native)
    out["A5b_shear_load_bearing"] = arm_shear_load_bearing(s, ag, native)
    out["A5c_no_bound_positive_control"] = arm_no_bound_control()
    out["A6_off_day"] = arm_off_day()

    a1, a3, a4 = out["A1_invariance"], out["A3_crux"], out["A4_floor"]
    out["OUTCOME"] = ("BOUNDED CROSSING" if (a1["correct"] >= 30 and a1["wrong_id"] == 0
                                             and out["A2_discrimination"]["exact0"]
                                             and a3["crux_pass"] and a4["floor_clean"])
                      else "DIAGNOSED NEGATIVE")
    os.makedirs(os.path.join(_ROOT, "results"), exist_ok=True)
    p = os.path.join(_ROOT, "results", "deformation_measure.json")
    with open(p, "w") as f:
        json.dump(out, f, indent=1)
    print(json.dumps({k: v for k, v in out.items() if k != "A4_floor"}, indent=1)[:4000])
    print("\nA4 floor:", {k: v for k, v in out["A4_floor"].items() if k != "detail"})
    print("\nOUTCOME:", out["OUTCOME"])
    print("wrote", p)
    return out


