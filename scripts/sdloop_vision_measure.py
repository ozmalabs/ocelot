def predicted_orbits(thetas) -> int:
    """#orbits of `thetas` (deg, mod 180) under the group generated by the HELD
    DimensionGenerators: rotation90 (θ→90−θ) and the reflections (θ→−θ).

    The group is {id, θ→90−θ, θ→−θ, θ→90+θ}. A generator only relates two orientations
    that are BOTH present — an image of θ outside the presented set is simply never
    observed. So the orbit count is the number of connected components. Pure arithmetic
    over the seed's own generator data; nothing is fitted to a measurement.
    """
    S = sorted({round(t % 180.0, 6) for t in thetas})
    idx = {t: i for i, t in enumerate(S)}
    parent = list(range(len(S)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[rb] = ra

    for t in S:
        for img in ((90.0 - t) % 180.0, (-t) % 180.0, (90.0 + t) % 180.0):
            img = round(img, 6)
            if img in idx:
                union(idx[t], idx[img])
    return len({find(i) for i in range(len(S))})


