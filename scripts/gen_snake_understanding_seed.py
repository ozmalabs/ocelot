"""Generator for seeds/snake_understanding.json — Stage 3: PLAY SNAKE FROM UNDERSTANDING (the jabberwock's
design), composed from primitives it already holds, NOT hand-coded aim/seek. Replaces world_prediction.json.

  · mark_salient: the SALIENT target is the static non-board region — axis_kind==invariant AND not ground.
    In Snake that residue is the FOOD (the head is controllable, the body moves -> autonomous, the board is
    ground). No hard-coded food value; salience falls out of the self/world/board discriminator.
  · choose_action: the SELF (the controllable region) picks the action by a death-gated Argmax over its four
    actions — roll the self forward by its learned control basis resp_<A>, score = -Manhattan(rolled-self,
    food), gate would_die (off the board, read from game.h/w) to -1e9. The seek FALLS OUT of "the move that
    most shrinks distance to the only not-me/not-board thing, without dying." Sets game.chosen_action.

Run: python3 scripts/gen_snake_understanding_seed.py
"""
from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ACTIONS = ["Up", "Down", "Left", "Right"]
NEG_INF = -1.0e9


def V(n): return {"type": "Var", "name": n}
def Lit(v): return {"type": "Lit", "value": v}
def Attr(node, k): return {"type": "Attr", "node": node, "key": k}
def P(node, k): return {"type": "Plus", "items": [Attr(node, k), Lit(0.0)]}     # None-safe numeric read
def And(items): return {"type": "And", "items": items}
def Or(items): return {"type": "Or", "items": items}
def Eq(a, b): return {"type": "Eq", "a": a, "b": b}
def Lt(a, b): return {"type": "Lt", "a": a, "b": b}
def Gt(a, b): return {"type": "Gt", "a": a, "b": b}
def Gte(a, b): return {"type": "Gte", "a": a, "b": b}
def Plus(items): return {"type": "Plus", "items": items}
def Minus(a, b): return {"type": "Minus", "a": a, "b": b}
def Neg(a): return {"type": "Neg", "arg": a}
def Max(items): return {"type": "Max", "items": items}
def Abs(x): return Max([x, Neg(x)])
def Ite(c, t, o): return {"type": "IfThenElse", "cond": c, "then": t, "other": o}

R, F, G = V("r"), V("food"), V("game")


def rolled(a):
    """(nr, nc) = the self rolled forward by its learned control basis resp_<a>."""
    nr = Plus([P(R, "cy"), P(R, f"resp_{a}_dr")])
    nc = Plus([P(R, "cx"), P(R, f"resp_{a}_dc")])
    return nr, nc


def would_die(nr, nc):
    """Off the board — extent read from the game node (h/w), not hard-coded."""
    hi_r = Minus(Attr(G, "h"), Lit(1.0))
    hi_c = Minus(Attr(G, "w"), Lit(1.0))
    return Or([Lt(nr, Lit(0.0)), Gt(nr, hi_r), Lt(nc, Lit(0.0)), Gt(nc, hi_c)])


def score(a):
    nr, nc = rolled(a)
    dist = Plus([Abs(Minus(nr, P(F, "cy"))), Abs(Minus(nc, P(F, "cx")))])
    return Ite(would_die(nr, nc), Lit(NEG_INF), Neg(dist))


def choose_term():
    sU, sD, sL, sR = (score(a) for a in ACTIONS)
    return Ite(And([Gte(sU, sD), Gte(sU, sL), Gte(sU, sR)]), Lit("Up"),
           Ite(And([Gte(sD, sL), Gte(sD, sR)]), Lit("Down"),
           Ite(Gte(sL, sR), Lit("Left"), Lit("Right"))))


def main():
    seed = {
        "id": "snake_understanding",
        "version": "1.0.0",
        "depends_on": ["nd_action_correlation"],
        "description": "Stage 3 — play Snake from understanding. The self (controllable region) seeks the "
                       "salient food (the static non-board region) and avoids death (off-board rollout), the "
                       "action chosen by a death-gated Argmax over the learned control basis resp_<A>. Composed "
                       "from the self/world/board discriminator + control + boundary; no hand-coded aim/seek. "
                       "Replaces world_prediction.json. Generated by scripts/gen_snake_understanding_seed.py.",
        "microtheory": {"name": "snake_understanding",
                        "description": "self seeks the only not-me/not-board thing (food) without dying — seek falls out of distance+safety"},
        "nodes": [], "edges": [], "productions": [],
        "rules": [
            {
                "name": "mark_salient",
                "comment": "The salient target = the static non-board region (axis_kind==invariant AND not "
                           "ground): in Snake that is the FOOD. LIVE (not a latch): salient is re-evaluated "
                           "every frame, so a region briefly invariant before it gains velocity (e.g. a head "
                           "the eye hadn't tracked yet) is UNMARKED once it reads controllable. No hard-coded "
                           "value; salience from the self/world/board discriminator.",
                "match": [["game", "has_region", "food"]],
                "where": Lit(True),
                "effects": [["set_attr", "food", "salient",
                             {"__term__": Ite(And([Eq(Attr(F, "axis_kind"), Lit("invariant")),
                                                   Lt(P(F, "is_ground"), Lit(0.5))]), Lit(1.0), Lit(0.0))}]],
            },
            {
                "name": "choose_action",
                "comment": "The self (the SINGLE-cell controllable region — the head; the body is also "
                           "controllable as it follows me, so pin self to count==1) picks the action whose "
                           "resp_<A> rollout most shrinks Manhattan distance to the salient food, gated by "
                           "would_die (off the board, extent from game.h/w). Seek falls out of distance+safety; "
                           "sets game.chosen_action.",
                "match": [["game", "has_region", "r"], ["game", "has_region", "food"]],
                "where": And([Eq(Attr(R, "axis_kind"), Lit("controllable")),
                              Lt(P(R, "count"), Lit(1.5)),
                              Gt(P(F, "salient"), Lit(0.5))]),
                "effects": [["set_attr", "game", "chosen_action", {"__term__": choose_term()}]],
            },
        ],
    }
    out = os.path.join(ROOT, "seeds", "snake_understanding.json")
    tmp = out + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(seed, fh, indent=1)
    json.load(open(tmp))
    os.replace(tmp, out)
    print(f"wrote + validated {os.path.relpath(out, ROOT)} ({len(seed['rules'])} rules)")


if __name__ == "__main__":
    main()
