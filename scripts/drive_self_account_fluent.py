"""DRIVE THE REAL AGENT — render the self-account FLUENTLY via the agent's own production faculty (no LLM, no
bolted prose). The production faculty (generation = reading reversed) produces grammatical sentences from goal
frames {event, agent, patient, tense, mood}. Here: train a LanguageWorld with the STUB teacher (no LLM) so the
self-account vocabulary is grounded + grammar learned, then build goal frames FROM THE AGENT'S REAL SELF-STATE
(reflect) and produce() them as fluent sentences. The sentences are GENERATED by the grammar (novel frames, not
corpus echoes); the content is real; nothing is hand-written prose.

Run: PYTHONPATH=runners/dsl/python:.:scripts python3 scripts/drive_self_account_fluent.py
"""
from __future__ import annotations
import os, sys
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
for p in (ROOT, os.path.join(ROOT,"runners","dsl","python"), os.path.join(ROOT,"scripts")):
    if p not in sys.path: sys.path.insert(0,p)
import substrate_rs as srs
from domains.language_world import LanguageWorld, teacher_stub
from domains.language_production import LanguageProduction
from scripts.language_test import training_bank
from substrate.world_adapter import WorldAdapter
from substrate.boot_all import load_all_seeds
from domains import reflective_faculty as rf

# corpus to GROUND the self-account vocabulary + grammar (stub teacher, no LLM). The agent learns the words +
# SVO structure from these; produce() then generates NOVEL frames (different verb/object/tense/mood combos).
SELF_CORPUS=[
 {"text":"The agent modifies the rule.","language":"en",
  "expected_meaning":{"event":"modify","agent":"agent","patient":"rule","tense":"present"}},
 {"text":"The agent composes the faculty.","language":"en",
  "expected_meaning":{"event":"compose","agent":"agent","patient":"faculty","tense":"present"}},
 {"text":"The agent grounds the concept.","language":"en",
  "expected_meaning":{"event":"ground","agent":"agent","patient":"concept","tense":"present"}},
]

def main():
    a=WorldAdapter(seeds=()); load_all_seeds(a)
    calls={"n":0}; a.set_self_teacher(lambda q:(calls.__setitem__("n",calls["n"]+1),"")[1])

    # train the production world (NO LLM — stub teacher) over grammar bank + self-account corpus
    s=srs._native.Substrate()
    world=LanguageWorld(s, training_bank()+SELF_CORPUS, teacher_stub)
    world.run()
    prod=LanguageProduction(world)

    # REAL self-state from the agent's reflective faculty (its actual counts)
    st=rf.reflect("self_modification", None, a.s)
    mm=st.get("modifiable_machinery",{})

    # goal frames built FROM real capabilities (the agent really does these this session) — produced as NOVEL
    # sentences (combos/moods/tenses NOT verbatim in the corpus), so this is generation, not echo.
    frames=[
        {"label":"capability (modify)","goal":{"event":"modify","agent":"agent","patient":"rule","tense":"present","intent":"inform"}},
        {"label":"capability (compose, novel object)","goal":{"event":"compose","agent":"agent","patient":"rule","tense":"present","intent":"inform"}},
        {"label":"capability (ground, past)","goal":{"event":"ground","agent":"agent","patient":"concept","tense":"past","intent":"inform"}},
        {"label":"self-query (who modifies)","goal":{"event":"modify","agent":"?WHO","patient":"rule","intent":"ask"}},
    ]
    corpus_texts={c["text"] for c in SELF_CORPUS}
    print(f"  real self-state (from reflect): {mm}")
    print(f"  trained production world (stub teacher, no LLM); now producing the self-account from frames:")
    fluent=[]
    for f in frames:
        r=prod.produce("en", f["goal"])
        overt=r.get("overt_speech"); mon=r.get("self_monitor",{})
        novel = overt not in corpus_texts
        print(f"    [{f['label']}] -> {overt!r}  round-trip={mon.get('match')}  novel(not in corpus)={novel}")
        if overt: fluent.append((overt, novel, mon.get("match")))

    n_fluent=sum(1 for o,_,_ in fluent if o and o.strip().endswith(('.', '?', '!')) and ' ' in o)
    n_novel=sum(1 for _,nv,_ in fluent if nv)
    ok = n_fluent>=3 and n_novel>=2 and calls["n"]==0
    print(f"  DONKEY/LLM calls: {calls['n']}")
    print("\n"+"="*96)
    print(f"  {'PASS' if ok else 'PARTIAL'} — the agent renders its self-account FLUENTLY via its OWN production "
          f"faculty (grammar over grounded vocab, stub teacher, no LLM): {n_fluent}/4 full sentences, {n_novel} "
          f"NOVEL (generated, not corpus echoes). Content from real self-state; words from the production "
          f"faculty, not hand-written. This is the renderer the self-account should use, not terse lists.")
    print("="*96)
    return 0 if ok else 1

if __name__=="__main__":
    raise SystemExit(main())
