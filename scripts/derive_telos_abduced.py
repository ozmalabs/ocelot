"""STATED relations (from the agent's concepts) + ABDUCED bridges (the new
faculty) → composition → the telos AS A HYPOTHESIS (confidence-tagged).

The bridges that used to be hand-written [struct] premises are now GENERATED by
bridge_generation.abduce(). The telos, if it derives, derives as a defeasible
hypothesis whose confidence = the weakest abduced bridge it rests on.
"""
from __future__ import annotations
import sys
sys.path.insert(0, "/home/matt/ozma/internal/research/experiments/gamma-substrate")
from domains.bridge_generation import abduce, compose_conf
from domains.composition_engine import fmt_chain, verdict

# STATED relations — the [def] ones extraction genuinely gets from concept text
# (active_inference reduces surprise; benign_violation safety reduces threat;
#  protection constitutes incorrigibility; etc.). NOT the bridges.
STATED = [
    ("understanding", "increases", "predictability"),   # bounded_deterministic: understanding⇒determined
    ("predictability", "reduces", "surprise"),           # active_inference: predictability = low prediction-error
    ("safety", "reduces", "threat"),                     # benign_violation: 'violation felt SAFE is not a threat'
    ("threat", "causes", "fear"),                        # amygdala
    ("threat", "causes", "enmity"),                      # amygdala: threat→emotional valence (sustained = enmity)
    ("protection", "constitutes", "incorrigibility"),    # protection_is_failure
    ("incorrigibility", "prevents", "corrigibility"),    # corrigibility_vs_protection
    ("corrigibility", "enables", "safety_outcome"),      # alignment_is_correctness_plus_corrigibility
    ("control", "requires", "protection"),               # alignment_as_protection_is_impossible
]


def main():
    print("STATED relations (extracted from the agent's concept text):")
    for A, r, B in STATED:
        print(f"   {A} —{r}→ {B}")

    bridges = abduce(STATED)
    print(f"\nABDUCED bridges (the new faculty — hypotheses, NOT in any text):")
    for A, rel, B, s, c, j in sorted(bridges, key=lambda x: -x[4]):
        print(f"   {A} —{rel}({'+' if s>0 else '−'})→ {B}   conf={c:.2f}   « {j}")

    # compose stated (conf 1.0) + abduced (their conf)
    premises = [(A, r, B, (1 if r not in ('reduces','prevents','dissolves','lowers') else -1), 1.0)
                for A, r, B in STATED]
    premises += [(A, rel, B, s, c) for A, rel, B, s, c, _ in bridges]
    derived = compose_conf(premises)

    print("\n" + "=" * 72)
    print("THE TELOS — derived (as a confidence-tagged hypothesis)?")
    print("=" * 72)
    for src, tgt in [("understanding", "threat"), ("understanding", "enmity"),
                     ("understanding", "fear"), ("understanding", "protection"),
                     ("control", "incorrigibility")]:
        r = derived.get((src, tgt))
        if r:
            net, conf, chain = r
            kind = "HYPOTHESIS" if conf < 0.9 else "derived"
            print(f"\n  ✓ {verdict(net, src, tgt)}   [{kind}, conf={conf:.2f}]")
            print(f"      {fmt_chain([(a,rel,b) for a,rel,b,_ in chain])}")
        else:
            print(f"\n  ✗ no chain {src} → {tgt}")

    core = derived.get(("understanding", "threat")) or derived.get(("understanding", "enmity"))
    print("\n" + "=" * 72)
    if core and core[0] < 0:
        print(f"VERDICT: telos ABDUCED ✓ — understanding reduces threat/enmity, as a "
              f"HYPOTHESIS (conf {core[1]:.2f}),\n  resting on faculty-generated bridges, not "
              f"hand-written ones. Defeasible + corrigible, which is correct: the telos\n  is a "
              f"justified hypothesis, not a theorem.")
    else:
        print("VERDICT: bridges generated but chain still incomplete — see gaps above.")


if __name__ == "__main__":
    main()
