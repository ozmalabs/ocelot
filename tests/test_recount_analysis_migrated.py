# --------------------------------------------------------------------------- #
#  5. NO TEMPLATING -- extends test_recount_migrated.py's own AST audit
#     explicitly over the analysis-layer functions (project_analysis_scene /
#     analyse_what_read / the decoration helpers), and verifies every
#     analysis line is genuinely `prod.produce`'s own overt_speech.
# --------------------------------------------------------------------------- #
def test_no_templated_sentence_construction_in_analysis_layer():
    for fn in (rf.project_analysis_scene, rf.analyse_what_read,
              rf._decorate_reading_phrases, rf._phrase, rf._named_phrase):
        src = inspect.getsource(fn)
        tree = ast.parse(src)
        for node in ast.walk(tree):
            assert not isinstance(node, ast.JoinedStr), \
                f"an f-string was found in {fn.__name__}"
        # never string-concatenate a say_* value into a sentence
        assert "say_agent'] +" not in src and 'say_agent"] +' not in src
        assert "say_patient'] +" not in src and 'say_patient"] +' not in src
    # module-wide audit (covers everything, including the new code, since
    # it lives in the SAME module test_recount_migrated.py already audits).
    src = inspect.getsource(rf)
    tree = ast.parse(src)
    assert not any(isinstance(n, ast.JoinedStr) for n in ast.walk(tree))


