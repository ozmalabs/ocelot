# The article the task itself specifies: a fund->oppose Trojan Horse (temporal
# + named-trope), a "with all due respect" conflicting-goals disclaimer, and
# (once the world supplies the oil company's actor class) an epistemic lean.
ANALYSIS_ARTICLE = ("The technology was funded by the oil company. "
                    "The technology was opposed by the oil company. "
                    "With all due respect, a spokesman called the critics misinformed.")

# A plain article with no disclaimer / no opposing-action pattern / no
