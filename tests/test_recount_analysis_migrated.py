def test_analysis_sentences_appear_for_trope_epistemic_conflicting_goals():
    """Updated (recount_analysis_realization.json v1.1.0): the tension slot now
    speaks the held FLUENT phrasing ('A Polite Hedge') instead of the raw
    title-cased slug ('Express Vs Avoid Social Cost') -- see
    test_recount_analysis_fluency_migrated.py for the ablation proof this is a
    held-data decision, not a Python literal. The temporal-conflict sentence
    ('Oil Company reversed ...') no longer appears ALONGSIDE the trope
    sentence for the SAME actor+pair -- analysis_suppress_superseded_temporal
    now suppresses it as redundant (the trope line already names the pattern)
    -- so n_readings stays 4 (the agent still HOLDS all four readings) while
    only 3 render as sentences. Both are genuine fluency improvements over the
    prior machine-like/redundant prose; see
    test_recount_analysis_fluency_migrated.py for the full ablation suite."""
    a, donkey = _fresh_agent_with_donkey()
    world, prod = _fresh_voice(a)
    result = rf.analyse_what_read(a, world, prod, ANALYSIS_ARTICLE,
                                  instruction="Recount what you read.", register="formal",
                                  actor_classes={"oil_company": "corporation"})
    joined = " ".join(result["analysis_lines"])
    # the NAMED trope (from held_trope_readings -> TropeReading.trope)
    assert "Trojan Horse" in joined, joined
    # the epistemic verdict (from assess_epistemic_lean -> EpistemicLeanReading.verdict)
    assert "Weak Deception" in joined, joined
    assert "reading" in joined.lower(), joined
    # the conflicting-goals disclaimer (from held_conflicting_goals)
    assert "With All Due Respect" in joined, joined
    assert "A Polite Hedge" in joined, joined
    assert "Express Vs Avoid Social Cost" not in joined, joined
    assert "Fund Then Oppose" not in joined, joined          # superseded by the trope line
    assert result["n_readings"] == 4, result["n_readings"]      # conflicting + temporal + trope + epistemic
    assert len(result["analysis_lines"]) == 3                   # temporal suppressed as redundant
    # EVERY analysis line passed LanguageProduction's OWN self-monitor round trip.
    assert all(result["accepted"][-3:]), result["accepted"]
    assert donkey["n"] == 0


