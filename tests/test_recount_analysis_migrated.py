# --------------------------------------------------------------------------- #
#  3. THE FRAME-CONSTRUCTION DECISION IS A GRAPH RULE, NOT PYTHON. Ablating
#     ONE reading type's realization rule drops ONLY that reading's sentence
#     -- the other reading types, realized by their OWN separate rules, are
#     unaffected. This is the source-level proof that recount_faculty.py's
#     Python never decides which reading field fills which produce-frame
#     slot (it is type-BLIND -- see project_analysis_scene's own docstring).
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize("rule_names,vanished,survives", [
    (("analysis_say_trope",), "Trojan Horse", "Weak Deception"),
    (("analysis_say_epistemic",), "Weak Deception", "Trojan Horse"),
    # v1.1.0: conflicting-goals realization is now TWO mutually-exclusive
    # rules (the fluent phrasing + the slug fallback -- see
    # test_recount_analysis_fluency_migrated.py); ablating only ONE no
    # longer removes the sentence, since the other still realizes it (a
    # genuine robustness improvement). "The realization" for this reading
    # type is both rules together.
    (("analysis_say_conflicting_goals", "analysis_say_conflicting_goals_fluent"),
     "With All Due Respect", "Trojan Horse"),
])
def test_frame_construction_is_a_rule_not_python(rule_names, vanished, survives):
    a, donkey = _fresh_agent_with_donkey()
    for rule_name in rule_names:
        assert _ablate_rule(a, rule_name)
    world, prod = _fresh_voice(a)
    result = rf.analyse_what_read(a, world, prod, ANALYSIS_ARTICLE,
                                  instruction="Recount what you read.", register="formal",
                                  actor_classes={"oil_company": "corporation"})
    joined = " ".join(result["analysis_lines"])
    assert vanished not in joined, joined
    assert survives in joined, joined
    # the reading itself is STILL held graph state -- ablating the rule
    # removes its REALIZATION, not the agent's own belief.
    assert (ag.held_trope_readings(a) or ag.held_conflicting_goals(a)
            or ag.held_epistemic_readings(a))
    assert donkey["n"] == 0


