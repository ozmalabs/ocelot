"""Independent finite worlds for P26 evidence selection and process search.

Public task opportunities contain only the world-owned affordances and goal.
Solvability, latent relations, and the witness remain scorer-side records so a
selector or search adapter cannot use them as an oracle.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import random
from types import MappingProxyType
from typing import Any, Iterable


EFFORT_CEILINGS = (1, 2, 4, 8, 16, 32, 64)
FAMILIES = ("cyclic_relation", "branching_relation")
RELATIONS = ("latent", "repeated", "irrelevant", "transferable", "unlearnable", "partial")


def _digest(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                    default=list).encode()).hexdigest()


@dataclass(frozen=True)
class EvidenceSearchPool:
    """One immutable opportunity pool and its separately held scorer labels."""
    split: str
    opportunities: tuple[dict[str, Any], ...]
    scorer_only: tuple[dict[str, Any], ...]
    pool_id: str
    pool_sha256: str

    def task_pool(self) -> tuple[dict[str, Any], ...]:
        """Return copies of the selector-visible opportunities only."""
        return tuple(_thaw(row) for row in self.opportunities)


def _freeze(value):
    if isinstance(value, dict):
        return MappingProxyType({key: _freeze(item) for key, item in value.items()})
    if isinstance(value, (list, tuple)):
        return tuple(_freeze(item) for item in value)
    return value


def _thaw(value):
    if hasattr(value, "items"):
        return {key: _thaw(item) for key, item in value.items()}
    if isinstance(value, tuple):
        return [_thaw(item) for item in value]
    return value


def _world(seed: int, family: str, draw: int, split: str,
           initial_state: tuple[int, ...] | None = None) -> tuple[dict, dict]:
    rng = random.Random(seed)
    n = 7 if family == "cyclic_relation" else 9
    # Native permutation primitives are generated by the world and named only
    # with generic IDs. Candidate syntax never participates in this generation.
    mechanism_rng = (random.Random(26_026 + FAMILIES.index(family))
                     if draw % len(RELATIONS) == 1 else rng)
    relation = RELATIONS[draw % len(RELATIONS)]
    step = 1 if relation == "transferable" else mechanism_rng.randrange(1, n)
    jump = 2 if relation == "transferable" else mechanism_rng.randrange(1, n)
    while jump == step:
        jump = mechanism_rng.randrange(1, n)
    actions = {"act_0": tuple((i + step) % n for i in range(n)),
               "act_1": tuple((i + jump) % n for i in range(n))}
    if family == "branching_relation":
        left, right = mechanism_rng.sample(range(n), 4)[:2], mechanism_rng.sample(range(n), 4)[2:]
        for action, pair in (("act_2", left), ("act_3", right)):
            permutation = list(range(n))
            permutation[pair[0]], permutation[pair[1]] = permutation[pair[1]], permutation[pair[0]]
            actions[action] = tuple(permutation)
    else:
        actions["act_2"] = tuple((i + (step + jump) % n) % n for i in range(n))
        actions["act_3"] = tuple((i - step) % n for i in range(n))
    if initial_state is None:
        start = list(range(n))
        rng.shuffle(start)
        start = tuple(start)
    else:
        start = tuple(map(int, initial_state))
        if len(start) != n or set(start) != set(range(n)):
            raise ValueError("initial state must be a permutation for the selected family")
    length = 2 + (draw % 3)
    witness = [rng.choice(tuple(actions)) for _ in range(length)]
    if relation == "partial":
        available = tuple(actions)[:-1]
    elif relation == "unlearnable":
        available = ("act_0",)
    else:
        available = tuple(actions)
    target = _apply_word(start, witness, actions)
    if relation != "unlearnable":
        for _ in range(64):
            candidate_word = [rng.choice(available) for _ in range(2 + rng.randrange(4))]
            candidate = _apply_word(start, candidate_word, actions)
            one_step = {_apply_word(start, (action,), actions) for action in available}
            if candidate not in one_step:
                witness, target = candidate_word, candidate
                break
    if relation == "unlearnable":
        impossible_map = list(range(n))
        impossible_map[0], impossible_map[1] = impossible_map[1], impossible_map[0]
        target = _apply_word(start, ("__impossible_swap__",),
                             {**actions, "__impossible_swap__": tuple(impossible_map)})
    else:
        target = _apply_word(start, witness, actions)
    solvable = relation != "unlearnable"
    world_id = f"p26:{family}:{split}:{seed}:{draw:04d}"
    legal_actions = tuple(available)
    public = {
        "world_id": world_id, "family": family, "split": split,
        "draw": draw, "difficulty_stratum": f"depth_{length}",
        "load_stratum": "low" if draw % 2 == 0 else "high",
        "capacity_stratum": f"states_{n}", "initial_state": start,
        "goal_state": target, "primitive_affordances": tuple(sorted(legal_actions)),
        "primitive_effects": {action: actions[action] for action in sorted(legal_actions)},
        "opportunity_ids": tuple(f"{world_id}:act:{action}" for action in sorted(legal_actions)),
        "context_features": {"surface_signal": rng.choice(("smooth", "rough")),
            "distractor_marker": rng.choice(("amber", "violet"))},
    }
    private = {"world_id": world_id, "relation_class": relation,
        "solvable": bool(solvable), "witness": tuple(witness) if solvable else (),
        "target_effect": target, "transition_count": len(actions),
        "transition_model": (), "action_effects": actions,
        "all_action_names": tuple(sorted(actions)), "legal_relation": relation,
        "relation_signature": _digest(actions),
        "transfer_relation": "rotate_positions_by_one"
            if draw % len(RELATIONS) == 3 else None,
        "irrelevant_feature_name": "distractor_marker"
            if draw % len(RELATIONS) == 2 else None}
    return public, private


def _apply_word(state, word, actions):
    current = tuple(state)
    for action in word:
        permutation = actions[action]
        result = [None] * len(current)
        for source, destination in enumerate(permutation):
            result[destination] = current[source]
        current = tuple(result)
    return current


def generate_evidence_search_pool(*, split: str, draws: Iterable[int],
                                  seed: int = 260_000, family: str | None = None,
                                  initial_state: Iterable[int] | None = None) -> EvidenceSearchPool:
    """Generate a fixed, candidate-name-independent pool and scorer archive."""
    if split not in {"train", "development", "validation", "heldout"}:
        raise ValueError("unknown split")
    if family is not None and family not in FAMILIES:
        raise ValueError("unknown world family")
    draw_ids = tuple(int(draw) for draw in draws)
    if len(set(draw_ids)) != len(draw_ids) or any(draw < 0 for draw in draw_ids):
        raise ValueError("draw IDs must be distinct nonnegative integers")
    opportunities, scorer = [], []
    for index, draw in enumerate(draw_ids):
        family_name = family or FAMILIES[(index // len(RELATIONS)) % len(FAMILIES)]
        world_seed = seed + (0 if split == "train" else
            {"development": 1_000_000, "validation": 2_000_000, "heldout": 3_000_000}[split]) + draw * 17 + index
        public, private = _world(world_seed, family_name, draw, split,
                                 tuple(initial_state) if initial_state is not None else None)
        opportunities.append(public)
        scorer.append(private)
    pool_id = f"p26:{split}:{seed}:{','.join(map(str, draw_ids))}"
    for task in opportunities:
        task["evidence_opportunities"] = tuple({
            "opportunity_key": opportunity_id, "pool_id": pool_id,
            "status": "eligible", "split": "training",
            "expected_outcome": "unknown", "answer_fields_absent": True,
            "sealed_labels_present": False, "source_epoch": 1,
            "model_epoch": 1, "frame_epoch": 1,
            "object_id": opportunity_id,
            "object_type": f"EvidenceState:{task['family']}",
            "action_kind": action, "feature_key": "state",
            "before_value": json.dumps(task["initial_state"], separators=(",", ":")),
            "fixed_rank": float(index), "random_rank": float(
                int(_digest([pool_id, opportunity_id])[:8], 16)),
        } for index, (opportunity_id, action) in enumerate(zip(
            task["opportunity_ids"], task["primitive_affordances"])))
    identity = {"pool_id": pool_id, "opportunities": opportunities, "scorer_only": scorer}
    return EvidenceSearchPool(split, tuple(_freeze(row) for row in opportunities),
        tuple(_freeze(row) for row in scorer), pool_id, _digest(identity))


def selector_views(pool: EvidenceSearchPool) -> dict[str, tuple[dict[str, Any], ...]]:
    """Materialize identical task IDs and affordances for all selector arms."""
    if pool.split not in {"train", "development"}:
        raise ValueError("selector access is forbidden for validation and held-out pools")
    return {name: pool.task_pool() for name in ("residual", "fixed", "random")}


def search_cost_curve(task: dict[str, Any], *, world_model: dict[str, Any],
                      ceilings: Iterable[int] = EFFORT_CEILINGS) -> dict:
    """Exhaustively enumerate finite action words, reporting every charged try.

    This is an external simulator scorer. Candidate identifiers/expressions are
    generated from the affordance set and never consulted to generate the goal.
    """
    effects = world_model.get("action_effects", {})
    actions = tuple(sorted(task["primitive_affordances"]))
    requested = tuple(int(value) for value in ceilings)
    if any(value <= 0 for value in requested) or tuple(sorted(set(requested))) != requested:
        raise ValueError("effort ceilings must be positive, strictly increasing values")
    if not requested:
        raise ValueError("at least one effort ceiling is required")
    max_depth = max(1, len(requested).bit_length() + 2)
    frontier = [(tuple(task["initial_state"]), ())]
    tried = 0
    seen_effects: set[tuple[int, ...]] = set()
    milestones = []
    max_work = requested[-1]
    solutions = []
    successful_attempts = 0
    for depth in range(1, max_depth + 1):
        next_frontier = []
        for state, word in frontier:
            for action in actions:
                if tried >= max_work:
                    break
                tried += 1
                permutation = effects.get(action)
                if permutation is None:
                    continue
                target_list = [None] * len(state)
                for source, destination in enumerate(permutation):
                    target_list[int(destination)] = state[source]
                target = tuple(target_list)
                effect = target
                seen_effects.add(effect)
                new_word = (*word, action)
                if target == tuple(task["goal_state"]):
                    solutions.append({"work": tried, "word": new_word})
                    successful_attempts += 1
                if depth < max_depth:
                    next_frontier.append((target, new_word))
                while len(milestones) < len(requested) and tried >= requested[len(milestones)]:
                    ceiling = requested[len(milestones)]
                    milestones.append({"effort_ceiling": ceiling,
                        "attempts": min(tried, ceiling), "unique_effect_coverage": len(seen_effects),
                        "success": any(item["work"] <= ceiling for item in solutions)})
            if tried >= max_work:
                break
        if tried >= max_work:
            break
        frontier = next_frontier
        if not frontier:
            break
    # Drain ceilings above finite exhaustion as explicit zero-work observations.
    exhausted = tried < max_work and not frontier
    while len(milestones) < len(requested):
        ceiling = requested[len(milestones)]
        milestones.append({"effort_ceiling": ceiling, "attempts": min(tried, ceiling),
            "unique_effect_coverage": len(seen_effects),
            "success": any(item["work"] <= ceiling for item in solutions)})
    return {"world_id": task["world_id"], "effort_curve": milestones,
        "attempts": tried, "unique_effect_coverage": len(seen_effects),
        "success_work": min((item["work"] for item in solutions), default=None),
        "failed_or_invalid_attempts": tried - successful_attempts,
        "finite_space_exhausted": exhausted,
        "finite_space_exhaustion_work": tried if exhausted else None}


class EvidenceSearchWorld:
    """Mechanical receipt boundary for selector-visible action opportunities."""

    def __init__(self, task: dict[str, Any], world_model: dict[str, Any]):
        if task.get("world_id") != world_model.get("world_id"):
            raise ValueError("task and scorer mechanics identify different worlds")
        self.task = task
        if any(tuple(task.get("primitive_effects", {}).get(action, ()))
               != tuple(world_model.get("action_effects", {}).get(action, ()))
               for action in task.get("primitive_affordances", ())):
            raise ValueError("task primitive affordances differ from scorer world")
        self._effects = world_model.get("action_effects", {})
        self._states = {str(row["opportunity_key"]): tuple(task["initial_state"])
                        for row in task.get("evidence_opportunities", ())}
        self._receipts = {}
        self.epoch = 0

    def execute(self, opportunity: dict[str, Any]):
        from evaluation.process_mastery.target_learning_worlds import WorldReceipt

        if opportunity.get("split") != "training":
            raise ValueError("only authorized training opportunities may be executed")
        key = str(opportunity.get("opportunity_key", ""))
        if key not in self._states:
            raise ValueError("opportunity is not owned by this world")
        before = self._states[key]
        declared_before = tuple(json.loads(opportunity["before_value"]))
        if before != declared_before:
            raise ValueError("opportunity has a stale world state")
        permutation = self._effects.get(str(opportunity["action_kind"]))
        if permutation is None:
            raise ValueError("action is not a world affordance at this state")
        target_list = [None] * len(before)
        for source, destination in enumerate(permutation):
            target_list[int(destination)] = before[source]
        target = tuple(target_list)
        self.epoch += 1
        self._states[key] = target
        receipt = WorldReceipt(
            event_id=f"{self.task['world_id']}:receipt:{self.epoch}:{key}",
            object_id=str(opportunity["object_id"]),
            object_type=str(opportunity["object_type"]),
            action_kind=str(opportunity["action_kind"]), feature_key="state",
            before_value=json.dumps(before, separators=(",", ":")),
            after_value=json.dumps(target, separators=(",", ":")), status="observed",
            action_authorized=True, world_epoch=self.epoch)
        self._receipts[receipt.event_id] = receipt
        return receipt

    def verify_receipt(self, receipt) -> bool:
        return self._receipts.get(getattr(receipt, "event_id", None)) == receipt
