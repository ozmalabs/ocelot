"""Independent finite worlds for P26 evidence selection and process search.

Public task opportunities contain only the world-owned affordances and goal.
Solvability, latent relations, and the witness remain scorer-side records so a
selector or search adapter cannot use them as an oracle.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import random
from typing import Any, Iterable


EFFORT_CEILINGS = (1, 2, 4, 8, 16, 32, 64)
FAMILIES = ("cyclic_relation", "branching_relation")
RELATIONS = ("latent", "repeated", "irrelevant", "transferable", "unlearnable", "partial")


def _digest(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                    default=list).encode()).hexdigest()


@dataclass(frozen=True)
class EvidenceSearchPool:
    """One immutable opportunity pool and its separately held scorer labels."""
    split: str
    opportunities: tuple[dict[str, Any], ...]
    scorer_only: tuple[dict[str, Any], ...]
    pool_id: str
    pool_sha256: str

    def task_pool(self) -> tuple[dict[str, Any], ...]:
        """Return copies of the selector-visible opportunities only."""
        return tuple(json.loads(json.dumps(row)) for row in self.opportunities)


def _world(seed: int, family: str, draw: int, split: str) -> tuple[dict, dict]:
    rng = random.Random(seed)
    n = 7 if family == "cyclic_relation" else 9
    # Actions are generated by the world and have generic IDs unrelated to a
    # target, candidate expression, or learner vocabulary.
    mechanism_rng = (random.Random(26_026 + FAMILIES.index(family))
                     if draw % len(RELATIONS) == 1 else rng)
    step = 1 if draw % len(RELATIONS) == 3 else mechanism_rng.randrange(1, n)
    jump = 2 if draw % len(RELATIONS) == 3 else mechanism_rng.randrange(1, n)
    while jump == step:
        jump = mechanism_rng.randrange(1, n)
    actions = {
        "act_0": {str(i): (i + step) % n for i in range(n)},
        "act_1": {str(i): (i + jump) % n for i in range(n)},
        "act_2": {str(i): (i * 2 + 1) % n for i in range(n)},
        "act_3": {str(i): (i * 3 + 2) % n for i in range(n)},
    }
    start = rng.randrange(n)
    relation = RELATIONS[draw % len(RELATIONS)]
    length = 2 + (draw % 3)
    witness = [rng.choice(tuple(actions)) for _ in range(length)]
    target = start
    for action in witness:
        target = actions[action][str(target)]
    one_step_targets = {int(mapping[str(start)]) for mapping in actions.values()}
    if relation != "unlearnable" and target in one_step_targets:
        for _ in range(64):
            candidate = start
            candidate_word = [rng.choice(tuple(actions)) for _ in range(2 + rng.randrange(4))]
            for action in candidate_word:
                candidate = actions[action][str(candidate)]
            if candidate not in one_step_targets:
                target, witness = candidate, candidate_word
                break
        if target in one_step_targets:
            target = next(state for state in range(n) if state not in one_step_targets)
    transitions = []
    for state in range(n):
        for action, mapping in actions.items():
            # A deterministic world-side dropout creates partial affordance
            # coverage in one stratum; the omitted transitions are not shown
            # to any arm as a hidden answer.
            if relation == "partial" and (state + int(action[-1])) % 5 == 0:
                continue
            transitions.append((state, action, int(mapping[str(state)])))
    solvable = relation != "unlearnable"
    if relation == "unlearnable":
        reachable = {start}
        while True:
            next_states = reachable | {dst for src, _act, dst in transitions if src in reachable}
            if next_states == reachable:
                break
            reachable = next_states
        impossible = [state for state in range(n) if state not in reachable]
        if impossible:
            target = impossible[0]
        else:
            # Restrict this task's legal transition graph so a scorer-only
            # impossible goal exists even when the full action set is cyclic.
            transitions = [row for row in transitions if row[0] == start and row[1] == "act_0"]
            reachable = {start, *(row[2] for row in transitions)}
            target = next(state for state in range(n) if state not in reachable)
    reachable = {start}
    while True:
        next_states = reachable | {dst for src, _act, dst in transitions if src in reachable}
        if next_states == reachable:
            break
        reachable = next_states
    if relation == "unlearnable" and target in reachable:
        transitions = [row for row in transitions if row[0] == start and row[1] == "act_0"]
        reachable = {start, *(row[2] for row in transitions)}
        target = next(state for state in range(n) if state not in reachable)
    if target in one_step_targets:
        target = next(state for state in range(n) if state not in one_step_targets)
    solvable = relation != "unlearnable" and target in reachable
    world_id = f"p26:{family}:{split}:{draw:04d}"
    public = {
        "world_id": world_id, "family": family, "split": split,
        "draw": draw, "difficulty_stratum": f"depth_{length}",
        "capacity_stratum": f"states_{n}", "initial_state": start,
        "goal_state": target, "primitive_affordances": actions,
        "transition_model": tuple(transitions),
        "opportunity_ids": (f"{world_id}:observe", f"{world_id}:act", f"{world_id}:transfer"),
        "context_features": {"surface_signal": rng.choice(("smooth", "rough")),
            "distractor_marker": rng.choice(("amber", "violet"))},
    }
    private = {"world_id": world_id, "relation_class": relation,
        "solvable": bool(solvable), "witness": tuple(witness) if solvable else (),
        "target_effect": target, "transition_count": len(transitions),
        "relation_signature": _digest(actions),
        "transfer_relation": "increment_by_one_mod_state_count"
            if draw % len(RELATIONS) == 3 else None,
        "irrelevant_feature_name": "distractor_marker"
            if draw % len(RELATIONS) == 2 else None}
    return public, private


def generate_evidence_search_pool(*, split: str, draws: Iterable[int],
                                  seed: int = 260_000) -> EvidenceSearchPool:
    """Generate a fixed, candidate-name-independent pool and scorer archive."""
    if split not in {"train", "development", "validation", "heldout"}:
        raise ValueError("unknown split")
    draw_ids = tuple(int(draw) for draw in draws)
    if len(set(draw_ids)) != len(draw_ids) or any(draw < 0 for draw in draw_ids):
        raise ValueError("draw IDs must be distinct nonnegative integers")
    opportunities, scorer = [], []
    for index, draw in enumerate(draw_ids):
        family = FAMILIES[(index // len(RELATIONS)) % len(FAMILIES)]
        world_seed = seed + (0 if split == "train" else
            {"development": 1_000_000, "validation": 2_000_000, "heldout": 3_000_000}[split]) + draw * 17 + index
        public, private = _world(world_seed, family, draw, split)
        opportunities.append(public)
        scorer.append(private)
    pool_id = f"p26:{split}:{seed}:{','.join(map(str, draw_ids))}"
    identity = {"pool_id": pool_id, "opportunities": opportunities}
    return EvidenceSearchPool(split, tuple(opportunities), tuple(scorer), pool_id, _digest(identity))


def selector_views(pool: EvidenceSearchPool) -> dict[str, tuple[dict[str, Any], ...]]:
    """Materialize identical task IDs and affordances for all selector arms."""
    if pool.split not in {"train", "development"}:
        raise ValueError("selector access is forbidden for validation and held-out pools")
    return {name: pool.task_pool() for name in ("residual", "fixed", "random")}


def search_cost_curve(task: dict[str, Any], *, ceilings: Iterable[int] = EFFORT_CEILINGS) -> dict:
    """Exhaustively enumerate finite action words, reporting every charged try.

    This is an external simulator scorer. Candidate identifiers/expressions are
    generated from the affordance set and never consulted to generate the goal.
    """
    model = {(int(src), action): int(dst)
             for src, action, dst in task["transition_model"]}
    actions = tuple(sorted(task["primitive_affordances"]))
    requested = tuple(int(value) for value in ceilings)
    if any(value <= 0 for value in requested) or tuple(sorted(set(requested))) != requested:
        raise ValueError("effort ceilings must be positive, strictly increasing values")
    if not requested:
        raise ValueError("at least one effort ceiling is required")
    max_depth = max(1, len(requested).bit_length() + 2)
    frontier = [(int(task["initial_state"]), ())]
    tried = 0
    seen_effects: set[tuple[int, int]] = set()
    milestones = []
    max_work = requested[-1]
    solutions = []
    successful_attempts = 0
    for depth in range(1, max_depth + 1):
        next_frontier = []
        for state, word in frontier:
            for action in actions:
                if tried >= max_work:
                    break
                tried += 1
                target = model.get((state, action))
                if target is None:
                    continue
                effect = (int(task["initial_state"]), target)
                seen_effects.add(effect)
                new_word = (*word, action)
                if target == int(task["goal_state"]):
                    solutions.append({"work": tried, "word": new_word})
                    successful_attempts += 1
                if depth < max_depth:
                    next_frontier.append((target, new_word))
                while len(milestones) < len(requested) and tried >= requested[len(milestones)]:
                    ceiling = requested[len(milestones)]
                    milestones.append({"effort_ceiling": ceiling,
                        "attempts": min(tried, ceiling), "unique_effect_coverage": len(seen_effects),
                        "success": any(item["work"] <= ceiling for item in solutions)})
            if tried >= max_work:
                break
        if tried >= max_work:
            break
        frontier = next_frontier
        if not frontier:
            break
    # Drain ceilings above the finite exhaustion point as explicit zero-work
    # remaining effort observations, retaining exhaustion rather than retries.
    exhausted = tried < max_work and not frontier
    while len(milestones) < len(requested):
        ceiling = requested[len(milestones)]
        milestones.append({"effort_ceiling": ceiling, "attempts": min(tried, ceiling),
            "unique_effect_coverage": len(seen_effects),
            "success": any(item["work"] <= ceiling for item in solutions)})
    return {"world_id": task["world_id"], "effort_curve": milestones,
        "attempts": tried, "unique_effect_coverage": len(seen_effects),
        "success_work": min((item["work"] for item in solutions), default=None),
        "failed_or_invalid_attempts": tried - successful_attempts,
        "finite_space_exhausted": exhausted,
        "finite_space_exhaustion_work": tried if exhausted else None}
