#!/usr/bin/env python3
"""Five-policy rank-order core for the blinded proposal-utility panel.

Input contains candidate bundles, train-only utility rows grouped by family,
and an evaluation family. This module never reads held-out scores.
"""
from __future__ import annotations
import copy,hashlib,json,random
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys_path=[str(ROOT),str(ROOT/'runners/dsl/python')]
import sys
sys.path[:0]=sys_path

def bundle_digest(candidate:dict)->str:
 rules={}
 for name,rule in sorted((candidate.get('rules') or {}).items()):
  value=copy.deepcopy(rule)
  if isinstance(value,dict):value.pop('name',None)
  rules[name]=value
 raw=json.dumps(rules,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()
 return 'sha256:'+hashlib.sha256(raw).hexdigest()

def descriptors(candidates:list[dict])->list[dict]:
 return [{'label':str(c['label']),'digest':bundle_digest(c),
          'targets':sorted((c.get('rules') or {}).keys()),
          'outcome_class':str(c.get('outcome_class') or '')} for c in candidates]

def _agent(worker:int,evaluation_family:str,rule_overrides:dict[str,dict]|None=None):
 from substrate.boot_core import boot_core
 from substrate.seed_loader import manifest_for
 import domains.reflective_faculty as rf
 sub,root=boot_core(seeds=());native=sub._inner
 task_seed={'shape_axis':'shape_decode_loop','recurrence':'minting_recurrence_ledger',
            'navigation':'grid_navigation','control_kind':'control_kinds'}[evaluation_family]
 for seed in ('relation_vocabulary','composer_dispatch','autonomy',task_seed):
  native.load_seed_manifest(manifest_for(seed),root)
 for name,variant in sorted((rule_overrides or {}).items()):
  rows=native.export_rules()
  active=[i for i,row in enumerate(rows) if row.get('name')==name and row.get('active',True)]
  if not active or not all(native.remove_rule(i) for i in reversed(active)):
   raise RuntimeError(f'could not install locked candidate-generation baseline for {name}')
  native.add_rule(variant)
 class Agent:
  def __init__(self,s,n):self.s=s;self.inner=s._inner;self.agent=n
 agent=Agent(sub,root)
 inducted=rf.induce_concern(agent,[['correct','DIVERGENCE','by','CANDIDATE']],name_hint=f'panel_rank_{worker}')
 grounded=rf.ground_concern(agent,[inducted['capability_key']])
 programs=[sub.node(n)['attrs'].get('name') for n in sub.nodes('Program')
           if str(sub.node(n)['attrs'].get('name','')).startswith('self_correct_rank_')]
 if not grounded.get('grounded') or not programs:raise RuntimeError('graph-authored rank Program missing')
 return sub,native,agent,{'grounded':grounded.get('grounded'),'served_by':grounded.get('served_by'),'programs':programs}

def _records(rows:list[dict],source_family:str)->list[dict]:
 out=[]
 for row in rows:
  if 'heldout' in row or 'heldout_score' in row or 'heldout_utility' in row:
   raise ValueError('held-out label found in a training record')
  out.append({'target_rule':str(row['target_rule']),'candidate_label':str(row['candidate_label']),
   'outcome_class':str(row.get('outcome_class') or ''),'task_utility':float(row['task_utility']),
   'candidate_digest':str(row.get('candidate_digest') or ''),'source':source_family})
 return out

def policy_orders(*,worker:int,evaluation_family:str,candidates:list[dict],
                  training_by_family:dict[str,list[dict]],random_seed:int,
                  rule_overrides:dict[str,dict]|None=None)->dict:
 """Return the five preregistered orders and trace using train outcomes only."""
 from domains.self_correct_dispatch import rank_candidates
 if evaluation_family not in training_by_family:raise ValueError('missing evaluation-family training rows for memo baseline')
 ds=descriptors(candidates);labels=[x['label'] for x in ds]
 if len(labels)<3 or len(labels)!=len(set(labels)):raise ValueError('candidate labels are insufficient or duplicated')
 default=list(labels)
 # Training-record labels refer only to candidates generated by their own family.
 target_train=_records(training_by_family[evaluation_family],evaluation_family)
 other=[]
 for family,rows in training_by_family.items():
  if family!=evaluation_family:other.extend(_records(rows,family))
 sub,native,agent,composer=_agent(worker,evaluation_family,rule_overrides)
 rank_started=__import__('time').perf_counter_ns()
 frozen=rank_candidates(agent,native,[copy.deepcopy(c) for c in candidates])
 frozen_ns=__import__('time').perf_counter_ns()-rank_started
 for record in other:sub.add_node('CorrectionOutcome',record)
 rank_started=__import__('time').perf_counter_ns()
 experienced=rank_candidates(agent,native,[copy.deepcopy(c) for c in candidates])
 experience_ns=__import__('time').perf_counter_ns()-rank_started
 traces={str(c['label']):copy.deepcopy(c.get('_self_correction_rank_trace')) for c in experienced}
 successes={}
 for row in target_train:
  label=row['candidate_label'];successes[label]=successes.get(label,0.0)+row['task_utility']
 memo_choice=next((label for label in default if successes.get(label,0.0)>0.0),None)
 memo=([memo_choice]+[label for label in default if label!=memo_choice]) if memo_choice else list(default)
 randomized=list(default);random.Random(int(random_seed)).shuffle(randomized)
 orders={'experience_rank':[str(c['label']) for c in experienced],
  'frozen_rank':[str(c['label']) for c in frozen],'default_order':default,
  'random_order':randomized,'target_memoization':memo}
 for name,order in orders.items():
  if len(order)!=len(labels) or set(order)!=set(labels):raise RuntimeError(f'{name} is not a permutation of the candidates')
 record={'worker':int(worker),'evaluation_family':evaluation_family,
  'candidate_descriptors':ds,'candidate_bundles':copy.deepcopy(candidates),
  'training_record_families':sorted(training_by_family),
  'experience_record_families':sorted(f for f in training_by_family if f!=evaluation_family),
  'target_memo_training_rows':len(target_train),'experience_training_rows':len(other),
  'composer':composer,'orders':orders,'experience_rank_traces':traces,
  'rank_timing_ns':{'frozen_rank':frozen_ns,'experience_rank':experience_ns},
  'random_seed':int(random_seed)}
 forbidden={'heldout','heldout_score','heldout_utility','heldout_outcomes','task_utility'}
 def walk(value):
  if isinstance(value,dict):
   if forbidden.intersection(value):return True
   return any(walk(v) for v in value.values())
  if isinstance(value,list):return any(walk(v) for v in value)
  return False
 # Training utilities occur in typed prior counts, not serialized in the order record.
 if walk(record):raise RuntimeError('order record contains scorer outcomes')
 return record

def main():
 payload=json.load(sys.stdin)
 result=policy_orders(**payload)
 print(json.dumps(result,sort_keys=True,separators=(',',':')))
if __name__=='__main__':main()
